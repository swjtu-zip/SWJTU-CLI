func iscitHomepageDate(anchor *goquery.Selection) (string, string) {
	if anchor == nil || anchor.Length() == 0 {
		return "", ""
	}
	// Each dashboard card has its own row. Do not climb to a containing dl or
	// tab pane: those containers hold several dates and would assign the first
	// sibling's date to every article.
	if row := anchor.Closest("li, dt, dd").First(); row.Length() > 0 {
		if date, publishedAt := iscitRowDate(row); date != "" {
			return date, publishedAt
		}
		if row.Closest(".newbox").Length() > 0 {
			if date, publishedAt := iscitDateValues(row.ChildrenFiltered("span").First().Text()); date != "" {
				return date, publishedAt
			}
		}
	}
	// The lead news card has no li; its publication date is the direct span in
	// the card's text block.
	if card := anchor.Closest(".newbox .col-md-5").First(); card.Length() > 0 {
		textBlock := card.ChildrenFiltered("div").First()
		if date, publishedAt := iscitDateValues(textBlock.ChildrenFiltered("span").First().Text()); date != "" {
			return date, publishedAt
		}
	}
	return "", ""
}

