func iscitResponseError(doc *goquery.Document) error {
	if doc == nil {
		return fmt.Errorf("iscit: empty response")
	}
	title := strings.ToLower(strings.Join(strings.Fields(doc.Find("title").First().Text()), " "))
	bodySelection := doc.Find("body").First().Clone()
	bodySelection.Find("script, style, noscript").Remove()
	body := strings.ToLower(strings.Join(strings.Fields(bodySelection.Text()), " "))
	for _, marker := range []string{
		"404", "403", "错误", "not found", "access denied", "访问限制", "访问被拒绝",
		"验证码", "附件下载", "登录", "login", "安全验证", "网站防火墙", "waf",
		"cloudflare", "just a moment", "challenge",
	} {
		if strings.Contains(title, marker) {
			return fmt.Errorf("iscit: source returned an error, login, or verification page")
		}
	}
	for _, marker := range []string{
		"页面未找到", "页面不存在", "请输入验证码", "验证码下载附件", "应用维护中",
		"暂无权限访问该资源", "请先登录", "请登录后", "登录页面", "安全验证",
		"请求被阻断", "请求报文存在语法错误", "网站防火墙", "access denied",
		"cloudflare", "just a moment", "403 forbidden", "404 not found",
	} {
		if strings.Contains(body, marker) {
			return fmt.Errorf("iscit: source returned an error or verification shell")
		}
	}
	// A JS app shell can return HTTP 200 with no server-rendered content. It
	// must not be mistaken for a valid empty feed or article.
	if doc.Find("#app, #root, #appu1").Length() > 0 &&
		doc.Find(".newbox, .xsbox, .daybox, .new-list, .aboutbox, .newxq-boxy, .v_news_content").Length() == 0 {
		return fmt.Errorf("iscit: source returned an error, login, or verification page")
	}
	return nil
}

// iscitFetchArticle is the live detail path. Parsing remains deterministic;
// this hook verifies every image/download URL against the source before the
// article is handed to callers. The CMS occasionally returns an HTTP 200 HTML
// challenge page for a download URL, so status alone is deliberately not
// treated as proof that a resource is real.
func iscitFetchArticle(articleURL string) (*model.Article, []byte, error) {
	fullURL, ok := iscitArticleURL(iscitCanonicalBaseURL, articleURL)
	if !ok {
		return nil, nil, fmt.Errorf("iscit: refusing non-local or non-detail URL %q", articleURL)
	}
	body, err := iscitFetchHTML(fullURL)
	if err != nil {
		return nil, nil, err
	}
	article, err := parseIscitArticle(body, iscitCanonicalBaseURL)
	if err != nil {
		return nil, body, err
	}
	iscitVerifyArticleImages(article, iscitCanonicalBaseURL)
	article.Attachments = iscitVerifyAttachments(article.Attachments, iscitCanonicalBaseURL)
	iscitSanitizeContentHTML(article, iscitCanonicalBaseURL)
	if strings.TrimSpace(article.Content) == "" && len(article.Images) == 0 && len(article.Attachments) == 0 {
		return nil, body, fmt.Errorf("iscit: article has no usable content or resources")
	}
	return article, body, nil
}

func parseIscitArticle(rawHTML []byte, baseURL string) (*model.Article, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(rawHTML)))
	if err != nil {
		return nil, fmt.Errorf("iscit: parse article HTML: %w", err)
	}
	if err := iscitResponseError(doc); err != nil {
		return nil, err
	}
	pageType := strings.TrimSpace(doc.Find(`meta[name="pageType"], meta[name="pagetype"]`).First().AttrOr("content", ""))
	if pageType != "3" {
		return nil, fmt.Errorf("iscit: page is not an article (pageType %q)", pageType)
	}
	headline := doc.Find(".newxq-boxy h2").First()
	if headline.Length() == 0 || strings.TrimSpace(headline.Text()) == "" {
		return nil, fmt.Errorf("iscit: article headline is missing")
	}
	content := iscitArticleContent(doc)
	if content.Length() == 0 {
		return nil, fmt.Errorf("iscit: article body container is missing")
	}
	if strings.TrimSpace(content.Text()) == "" && content.Find("img, table, a, object, iframe").Length() == 0 {
		return nil, fmt.Errorf("iscit: article body is empty")
	}

	article, err := parseBodaArticle(rawHTML, baseURL)
	if err != nil {
		return nil, err
	}
	article.Title = cleanTitle(headline.Text())
	article.Type = iscitArticleType(doc, baseURL)
	article.Date, article.PublishedAt = iscitArticlePublication(doc)
	article.Content = extractBodaContentText(content)

	// Rebuild resource fields from the site-specific body scope. The generic
	// parser does not see this template's attachment block outside
	// .v_news_content, and its ContentHTML must retain resolved URLs.
	article.Images = nil
	article.Attachments = nil
	iscitFinalizeContent(article, content, baseURL)
	main := content.Closest(`form[name="_newscontent_fromname"]`).First()
	if main.Length() == 0 {
		main = content.Closest(".col-sm-8, .col-sm-9").First()
	}
	iscitAppendAttachments(article, main, baseURL)
	normalizeArticlePublishedAt(article)
	return article, nil
}

