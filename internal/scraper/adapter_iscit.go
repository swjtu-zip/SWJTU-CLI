func iscitFinalizeContent(article *model.Article, content *goquery.Selection, baseURL string) {
	if article == nil || content == nil || content.Length() == 0 {
		return
	}
	seenImages := make(map[string]bool)
	content.Find("img[src], img[orisrc]").Each(func(_ int, image *goquery.Selection) {
		src := strings.TrimSpace(image.AttrOr("src", ""))
		if src == "" {
			src = strings.TrimSpace(image.AttrOr("orisrc", ""))
		}
		resolved := cleanURL(resolveURL(baseURL, src))
		if resolved == "" {
			return
		}
		image.SetAttr("src", resolved)
		if !seenImages[resolved] {
			seenImages[resolved] = true
			article.Images = append(article.Images, resolved)
		}
	})
	seenAttachments := make(map[string]bool)
	content.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		iscitAddAttachment(article, seenAttachments, anchor, baseURL)
	})
	if html, err := content.Html(); err == nil {
		article.ContentHTML = html
	}
}

func iscitAppendAttachments(article *model.Article, scope *goquery.Selection, baseURL string) {
	if article == nil || scope == nil || scope.Length() == 0 {
		return
	}
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		seen[attachment.URL] = true
	}
	scope.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		iscitAddAttachment(article, seen, anchor, baseURL)
	})
}

func iscitAddAttachment(article *model.Article, seen map[string]bool, anchor *goquery.Selection, baseURL string) {
	if article == nil || anchor == nil || anchor.Length() == 0 {
		return
	}
	href := strings.TrimSpace(anchor.AttrOr("href", ""))
	if href == "" || !iscitLooksLikeAttachment(anchor, href) {
		return
	}
	resolved := cleanURL(resolveURL(baseURL, href))
	if resolved == "" || seen[resolved] {
		return
	}
	name := iscitAttachmentName(anchor, href)
	if name == "" {
		return
	}
	seen[resolved] = true
	article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: resolved})
	anchor.SetAttr("href", resolved)
}

func iscitLooksLikeAttachment(anchor *goquery.Selection, href string) bool {
	lowerHref := strings.ToLower(href)
	if strings.Contains(lowerHref, "download.jsp") || strings.Contains(lowerHref, "downloadattachurl") || strings.TrimSpace(anchor.AttrOr("download", "")) != "" {
		return true
	}
	name := strings.TrimSpace(anchor.AttrOr("download", ""))
	if iscitAttachmentRe.MatchString(lowerHref) || iscitAttachmentRe.MatchString(name) {
		return true
	}
	text := strings.Join(strings.Fields(anchor.Text()), " ")
	if iscitAttachmentRe.MatchString(text) {
		return true
	}
	parentText := strings.Join(strings.Fields(anchor.Parent().Text()), " ")
	return strings.Contains(parentText, "附件") && !strings.Contains(lowerHref, "/info/")
}

func iscitAttachmentName(anchor *goquery.Selection, href string) string {
	for _, attr := range []string{"download", "data-filename", "data-name", "name", "title"} {
		if value := strings.Join(strings.Fields(anchor.AttrOr(attr, "")), " "); value != "" {
			return value
		}
	}
	if value := strings.Join(strings.Fields(anchor.Text()), " "); value != "" {
		return strings.Trim(value, "【】[]")
	}
	if parsed, err := url.Parse(href); err == nil {
		path := strings.TrimRight(parsed.Path, "/")
		if index := strings.LastIndex(path, "/"); index >= 0 {
			return path[index+1:]
		}
		return path
	}
	return ""
}
