func iscitFinalizeContent(article *model.Article, content *goquery.Selection, baseURL string) {
	if article == nil || content == nil || content.Length() == 0 {
		return
	}
	seenImages := make(map[string]bool)
	content.Find("img").Each(func(_ int, image *goquery.Selection) {
		candidates := iscitImageCandidateURLs(image, baseURL)
		if len(candidates) == 0 {
			image.Remove()
			return
		}
		image.SetAttr("src", candidates[0])
		if !seenImages[candidates[0]] {
			seenImages[candidates[0]] = true
			article.Images = append(article.Images, candidates[0])
		}
	})
	seenAttachments := make(map[string]bool)
	content.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		iscitAddAttachment(article, seenAttachments, anchor, baseURL)
	})
	if html, err := content.Html(); err == nil {
		article.ContentHTML = html
	}
}

func iscitAppendAttachments(article *model.Article, scope *goquery.Selection, baseURL string) {
	if article == nil || scope == nil || scope.Length() == 0 {
		return
	}
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		seen[attachment.URL] = true
	}
	scope.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		iscitAddAttachment(article, seen, anchor, baseURL)
	})
}

func iscitAddAttachment(article *model.Article, seen map[string]bool, anchor *goquery.Selection, baseURL string) {
	if article == nil || anchor == nil || anchor.Length() == 0 {
		return
	}
	href := strings.TrimSpace(anchor.AttrOr("href", ""))
	if href == "" || !iscitLooksLikeAttachment(anchor, href) {
		return
	}
	resolved := iscitResourceURL(baseURL, href)
	if resolved == "" || seen[resolved] {
		return
	}
	name := iscitAttachmentName(anchor, href)
	if name == "" {
		return
	}
	seen[resolved] = true
	article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: resolved})
	anchor.SetAttr("href", resolved)
}

func iscitLooksLikeAttachment(anchor *goquery.Selection, href string) bool {
	lowerHref := strings.ToLower(href)
	if strings.Contains(lowerHref, "download.jsp") || strings.Contains(lowerHref, "downloadattachurl") || strings.TrimSpace(anchor.AttrOr("download", "")) != "" {
		return true
	}
	name := strings.TrimSpace(anchor.AttrOr("download", ""))
	if iscitAttachmentRe.MatchString(lowerHref) || iscitAttachmentRe.MatchString(name) {
		return true
	}
	text := strings.Join(strings.Fields(anchor.Text()), " ")
	if iscitAttachmentRe.MatchString(text) {
		return true
	}
	parentText := strings.Join(strings.Fields(anchor.Parent().Text()), " ")
	return strings.Contains(parentText, "附件") && !strings.Contains(lowerHref, "/info/")
}

func iscitAttachmentName(anchor *goquery.Selection, href string) string {
	for _, attr := range []string{"download", "data-filename", "data-name", "name", "title"} {
		if value := strings.Join(strings.Fields(anchor.AttrOr(attr, "")), " "); value != "" {
			return value
		}
	}
	if value := strings.Join(strings.Fields(anchor.Text()), " "); value != "" {
		return value
	}
	if parsed, err := url.Parse(href); err == nil {
		path := strings.TrimRight(parsed.Path, "/")
		if index := strings.LastIndex(path, "/"); index >= 0 {
			return path[index+1:]
		}
		return path
	}
	return ""
}

func iscitImageCandidateURLs(image *goquery.Selection, baseURL string) []string {
	if image == nil || image.Length() == 0 {
		return nil
	}
	seen := make(map[string]bool)
	urls := make([]string, 0, 3)
	for _, attr := range []string{"src", "data-src", "data-original", "data-lazy-src", "orisrc"} {
		raw := strings.TrimSpace(image.AttrOr(attr, ""))
		resolved := iscitResourceURL(baseURL, raw)
		if resolved == "" || seen[resolved] {
			continue
		}
		seen[resolved] = true
		urls = append(urls, resolved)
	}
	return urls
}

// iscitResourceURL resolves content resources, including legitimate external
// images or files, while rejecting pseudo-URLs and common CMS placeholders.
// Article URLs use the stricter same-origin iscitArticleURL path separately.
func iscitResourceURL(baseURL, raw string) string {
	raw = strings.TrimSpace(raw)
	if raw == "" || bodaIsPseudoResourceHref(raw) {
		return ""
	}
	resolved := bodaResourceURL(baseURL, raw)
	parsed, err := url.Parse(resolved)
	if err != nil || parsed.Hostname() == "" || (parsed.Scheme != "http" && parsed.Scheme != "https") {
		return ""
	}
	resourceText := strings.ToLower(parsed.Path + "?" + parsed.RawQuery)
	for _, marker := range []string{"/captcha", "/verify", "/login", "/signin", "/placeholder", "/transparent", "/spacer", "/blank", "/loading", "/pixel.gif"} {
		if strings.Contains(resourceText, marker) {
			return ""
		}
	}
	parsed.Fragment = ""
	return cleanURL(parsed.String())
}

func iscitVerifyArticleImages(article *model.Article, baseURL string) {
	if article == nil {
		return
	}
	valid := make([]string, 0, len(article.Images))
	validSet := make(map[string]bool)
	checked := make(map[string]bool)
	usable := make(map[string]bool)
	verify := func(raw string) bool {
		resolved := iscitResourceURL(baseURL, raw)
		if resolved == "" {
			return false
		}
		if checked[resolved] {
			return usable[resolved]
		}
		checked[resolved] = true
		body, contentType, err := iscitFetchResource(resolved, baseURL, true)
		usable[resolved] = err == nil && iscitResourceBodyIsUsable(contentType, body, resolved, true)
		return usable[resolved]
	}
	add := func(raw string) bool {
		resolved := iscitResourceURL(baseURL, raw)
		if !verify(resolved) {
			return false
		}
		if !validSet[resolved] {
			validSet[resolved] = true
			valid = append(valid, resolved)
		}
		return true
	}

	if strings.TrimSpace(article.ContentHTML) != "" {
		if doc, err := goquery.NewDocumentFromReader(strings.NewReader("<div id=\"iscit-content-root\">" + article.ContentHTML + "</div>")); err == nil {
			doc.Find("#iscit-content-root img").Each(func(_ int, image *goquery.Selection) {
				for _, candidate := range iscitImageCandidateURLs(image, baseURL) {
					if add(candidate) {
						break
					}
				}
			})
		}
	}
	if len(valid) == 0 {
		for _, image := range article.Images {
			add(image)
		}
	}
	article.Images = valid
}

func iscitVerifyImages(images []string, baseURL string) []string {
	verified := make([]string, 0, len(images))
	seen := make(map[string]bool)
	for _, raw := range images {
		resolved := iscitResourceURL(baseURL, raw)
		if resolved == "" || seen[resolved] {
			continue
		}
		body, contentType, err := iscitFetchResource(resolved, baseURL, true)
		if err != nil || !iscitResourceBodyIsUsable(contentType, body, resolved, true) {
			continue
		}
		seen[resolved] = true
		verified = append(verified, resolved)
	}
	return verified
}

func iscitVerifyAttachments(attachments []model.Attachment, baseURL string) []model.Attachment {
	verified := make([]model.Attachment, 0, len(attachments))
	seen := make(map[string]bool)
	for _, attachment := range attachments {
		resolved := iscitResourceURL(baseURL, attachment.URL)
		if resolved == "" || seen[resolved] {
			continue
		}
		body, contentType, err := iscitFetchResource(resolved, baseURL, false)
		if err != nil || !iscitResourceBodyIsUsable(contentType, body, attachment.Name+" "+resolved, false) {
			continue
		}
		attachment.URL = resolved
		attachment.Size = strconv.Itoa(len(body))
		seen[resolved] = true
		verified = append(verified, attachment)
	}
	return verified
}

func iscitFetchResource(rawURL, baseURL string, image bool) ([]byte, string, error) {
	resolved := iscitResourceURL(baseURL, rawURL)
	if resolved == "" {
		return nil, "", fmt.Errorf("iscit: refusing invalid resource %q", rawURL)
	}
	req, err := http.NewRequest(http.MethodGet, resolved, nil)
	if err != nil {
		return nil, "", fmt.Errorf("iscit: create resource request: %w", err)
	}
	req.Header.Set("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36")
	if image {
		req.Header.Set("Accept", "image/avif,image/webp,image/apng,image/*,*/*;q=0.8")
	} else {
		req.Header.Set("Accept", "application/octet-stream,application/pdf,application/zip,*/*;q=0.8")
	}
	req.Header.Set("Referer", strings.TrimRight(strings.TrimSpace(baseURL), "/")+"/")

	client := http.Client{}
	if defaultClient != nil {
		client = *defaultClient
	}
	client.CheckRedirect = func(next *http.Request, via []*http.Request) error {
		if len(via) == 0 {
			return nil
		}
		previous := via[len(via)-1]
		if (next.URL.Scheme != "http" && next.URL.Scheme != "https") ||
			!strings.EqualFold(next.URL.Hostname(), previous.URL.Hostname()) {
			return http.ErrUseLastResponse
		}
		return nil
	}
	response, err := client.Do(req)
	if err != nil {
		return nil, "", fmt.Errorf("iscit: fetch resource %s: %w", resolved, err)
	}
	defer response.Body.Close()
	contentType := response.Header.Get("Content-Type")
	if response.StatusCode != http.StatusOK {
		return nil, contentType, fmt.Errorf("iscit: resource %s: HTTP %d", resolved, response.StatusCode)
	}
	if strings.TrimSpace(contentType) == "" {
		return nil, contentType, fmt.Errorf("iscit: resource %s has no content type", resolved)
	}
	if response.ContentLength > iscitMaxResourceBytes {
		return nil, contentType, fmt.Errorf("iscit: resource %s exceeds %d bytes", resolved, iscitMaxResourceBytes)
	}
	body, err := io.ReadAll(io.LimitReader(response.Body, iscitMaxResourceBytes+1))
	if err != nil {
		return nil, contentType, fmt.Errorf("iscit: read resource %s: %w", resolved, err)
	}
	if len(body) > iscitMaxResourceBytes {
		return nil, contentType, fmt.Errorf("iscit: resource %s exceeds %d bytes", resolved, iscitMaxResourceBytes)
	}
	return body, contentType, nil
}

func iscitResourceBodyIsUsable(contentType string, body []byte, nameOrURL string, image bool) bool {
	if len(body) == 0 {
		return false
	}
	mediaType := strings.ToLower(strings.TrimSpace(strings.Split(contentType, ";")[0]))
	if mediaType == "" {
		return false
	}
	probe := body
	if len(probe) > 4096 {
		probe = probe[:4096]
	}
	if iscitResourceShellRe.Match(probe) {
		return false
	}
	magic := iscitResourceMagic(body)
	if image {
		return iscitImageContentTypeMatches(mediaType, magic)
	}

	lowerName := strings.ToLower(nameOrURL)
	switch {
	case strings.Contains(lowerName, ".pdf") || mediaType == "application/pdf" || strings.HasSuffix(mediaType, "+pdf"):
		return magic == "pdf"
	case strings.Contains(lowerName, ".docx") || strings.Contains(lowerName, ".xlsx") || strings.Contains(lowerName, ".pptx") || strings.Contains(mediaType, "wordprocessingml") || strings.Contains(mediaType, "spreadsheetml") || strings.Contains(mediaType, "presentationml"):
		return magic == "zip"
	case strings.Contains(lowerName, ".doc") || strings.Contains(lowerName, ".xls") || strings.Contains(lowerName, ".ppt") || strings.Contains(lowerName, ".wps") || mediaType == "application/msword" || mediaType == "application/vnd.ms-excel" || mediaType == "application/vnd.ms-powerpoint":
		return magic == "ole"
	case strings.Contains(lowerName, ".zip") || strings.Contains(lowerName, ".rar") || strings.Contains(lowerName, ".7z") || mediaType == "application/zip" || mediaType == "application/x-rar-compressed" || mediaType == "application/x-7z-compressed":
		return magic == "zip" || magic == "rar" || magic == "7z"
	case strings.Contains(lowerName, ".rtf") || mediaType == "application/rtf":
		return bytes.HasPrefix(bytes.TrimSpace(body), []byte("{\\rtf"))
	case strings.Contains(lowerName, ".txt") || strings.Contains(lowerName, ".csv"):
		return (strings.HasPrefix(mediaType, "text/") && mediaType != "text/html" && mediaType != "text/xml") || mediaType == "application/octet-stream"
	default:
		return !strings.HasPrefix(mediaType, "text/") && mediaType != "application/xhtml+xml" && mediaType != "application/json" && mediaType != "application/xml" && magic != ""
	}
}

func iscitResourceMagic(body []byte) string {
	switch {
	case bytes.HasPrefix(body, []byte("%PDF-")):
		return "pdf"
	case len(body) >= 4 && (bytes.Equal(body[:4], []byte{0x50, 0x4b, 0x03, 0x04}) || bytes.Equal(body[:4], []byte{0x50, 0x4b, 0x05, 0x06}) || bytes.Equal(body[:4], []byte{0x50, 0x4b, 0x07, 0x08})):
		return "zip"
	case len(body) >= 8 && bytes.Equal(body[:8], []byte{0xd0, 0xcf, 0x11, 0xe0, 0xa1, 0xb1, 0x1a, 0xe1}):
		return "ole"
	case len(body) >= 3 && bytes.Equal(body[:3], []byte{0xff, 0xd8, 0xff}):
		return "jpeg"
	case len(body) >= 8 && bytes.Equal(body[:8], []byte{0x89, 'P', 'N', 'G', '\r', '\n', 0x1a, '\n'}):
		return "png"
	case len(body) >= 6 && (bytes.Equal(body[:6], []byte("GIF87a")) || bytes.Equal(body[:6], []byte("GIF89a"))):
		return "gif"
	case len(body) >= 12 && bytes.Equal(body[:4], []byte("RIFF")) && bytes.Equal(body[8:12], []byte("WEBP")):
		return "webp"
	case len(body) >= 2 && bytes.Equal(body[:2], []byte("BM")):
		return "bmp"
	case len(body) >= 4 && (bytes.Equal(body[:4], []byte{'I', 'I', '*', 0}) || bytes.Equal(body[:4], []byte{'M', 'M', 0, '*'})):
		return "tiff"
	case len(body) >= 7 && bytes.Equal(body[:7], []byte{'R', 'a', 'r', '!', 0x1a, 0x07, 0x00}):
		return "rar"
	case len(body) >= 8 && bytes.Equal(body[:8], []byte{'R', 'a', 'r', '!', 0x1a, 0x07, 0x01, 0x00}):
		return "rar"
	case len(body) >= 6 && bytes.Equal(body[:6], []byte{'7', 'z', 0xbc, 0xaf, 0x27, 0x1c}):
		return "7z"
	default:
		return ""
	}
}

func iscitImageContentTypeMatches(mediaType, magic string) bool {
	switch mediaType {
	case "image/jpeg", "image/jpg", "image/pjpeg":
		return magic == "jpeg"
	case "image/png":
		return magic == "png"
	case "image/gif":
		return magic == "gif"
	case "image/webp":
		return magic == "webp"
	case "image/bmp":
		return magic == "bmp"
	case "image/tiff":
		return magic == "tiff"
	default:
		return false
	}
}

func iscitSanitizeContentHTML(article *model.Article, baseURL string) {
	if article == nil || strings.TrimSpace(article.ContentHTML) == "" {
		return
	}
	validImages := make(map[string]bool, len(article.Images))
	for _, image := range article.Images {
		if resolved := iscitResourceURL(baseURL, image); resolved != "" {
			validImages[resolved] = true
		}
	}
	validAttachments := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		if resolved := iscitResourceURL(baseURL, attachment.URL); resolved != "" {
			validAttachments[resolved] = true
		}
	}
	doc, err := goquery.NewDocumentFromReader(strings.NewReader("<div id=\"iscit-content-root\">" + article.ContentHTML + "</div>"))
	if err != nil {
		return
	}
	content := doc.Find("#iscit-content-root").First()
	content.Find("img").Each(func(_ int, image *goquery.Selection) {
		resolved := ""
		for _, candidate := range iscitImageCandidateURLs(image, baseURL) {
			if validImages[candidate] {
				resolved = candidate
				break
			}
		}
		if resolved == "" {
			image.Remove()
			return
		}
		image.SetAttr("src", resolved)
		for _, attr := range []string{"data-src", "data-original", "data-lazy-src", "orisrc", "vsbhref", "vurl"} {
			image.RemoveAttr(attr)
		}
	})
	content.Find("a[href]").Each(func(_ int, link *goquery.Selection) {
		href := strings.TrimSpace(link.AttrOr("href", ""))
		if !iscitLooksLikeAttachment(link, href) {
			return
		}
		resolved := iscitResourceURL(baseURL, href)
		if resolved == "" || !validAttachments[resolved] {
			link.RemoveAttr("href")
			return
		}
		link.SetAttr("href", resolved)
	})
	if html, err := content.Html(); err == nil {
		article.ContentHTML = html
	}
}
