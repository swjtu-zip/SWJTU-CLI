// bioeng.swjtu.edu.cn uses the Visual SiteBuilder CMS, but its home page is
// a dashboard and its list rows are <dl>s. The generic Boda parser either
// misses those rows or scans the home-page carousel as if it were a news
// list, so keep the site-specific boundaries here.
func init() {
	registerAdapter("bioeng", SiteAdapter{
		SubPages:     bioengSubPages,
		ParseList:    parseAdapter_bioengList,
		ParseArticle: parseAdapter_bioengArticle,
		PageURL:      bioengPageURL,
		TotalPages:   bioengTotalPages,
	})
}

