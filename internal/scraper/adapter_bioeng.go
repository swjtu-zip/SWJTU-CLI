var (
	bioengArticlePathRe = regexp.MustCompile(`(?i)^/info/\d+/\d+\.html?$`)
	bioengDateRe        = regexp.MustCompile(`(20\d{2})\s*(?:年|[-/.])\s*(\d{1,2})\s*(?:月|[-/.])\s*(\d{1,2})\s*日?`)
	bioengClockRe       = regexp.MustCompile(`\d{1,2}\s*:\s*\d{2}`)
	bioengMetaLabelRe   = regexp.MustCompile(`(来源|作者|编辑|责编|摄影|日期|发布时间|点击数)\s*[:：]\s*`)
)

// bioengPageURL maps the logical page number (1 = newest) to the reversed
// filenames generated by the site. For example, xydt.htm advertises 47
// pages and its logical page 2 is xydt/46.htm, while the last page is
// xydt/1.htm.
func bioengPageURL(baseURL, slug string, page, totalPages int, extension string) string {
	baseURL = strings.TrimRight(baseURL, "/")
	slug = strings.Trim(slug, "/")
	if page < 1 || (totalPages > 0 && page > totalPages) {
		return ""
	}
	if page == 1 {
		return fmt.Sprintf("%s/%s%s", baseURL, slug, extension)
	}
	if totalPages <= 1 {
		return ""
	}
	filePage := totalPages - page + 1
	if filePage < 1 {
		return ""
	}
	return fmt.Sprintf("%s/%s/%d%s", baseURL, slug, filePage, extension)
}

func parseAdapter_bioengList(html []byte, baseURL string) ([]model.NewsItem, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(html)))
	if err != nil {
		return nil, fmt.Errorf("parse bioeng list: %w", err)
	}

	// index.htm is a dashboard. Its six .news .list panels are real feeds;
	// the preceding .main_visual carousel is intentionally outside this scope.
	if homeLists := doc.Find(".news > .con > .list"); homeLists.Length() > 0 {
		items := parseBioengHomeLists(homeLists, baseURL)
		if len(items) == 0 {
			return nil, fmt.Errorf("bioeng home page has no article rows")
		}
		return items, nil
	}

	// All article-list pages use the same narrow content container. Selecting
	// the row, rather than every info/ link in the document, excludes the
	// header, side navigation, breadcrumb, footer and related links.
	rows := doc.Find(".content dl")
	if rows.Length() == 0 {
		return nil, fmt.Errorf("bioeng page has no article list rows")
	}

	pageType := bioengPageType(doc)
	items := make([]model.NewsItem, 0, rows.Length())
	seen := make(map[string]bool, rows.Length())
	rows.Each(func(_ int, row *goquery.Selection) {
		anchor := bioengRowArticleAnchor(row, baseURL)
		if anchor == nil || anchor.Length() == 0 {
			return
		}
		fullURL, ok := bioengArticleURL(baseURL, anchor.AttrOr("href", ""))
		if !ok || seen[fullURL] {
			return
		}

		title := bioengListTitle(anchor, fullURL, baseURL)
		if title == "" || !isValidNewsTitle(title) || len([]rune(title)) > 160 {
			return
		}
		date, publishedAt := bioengListDate(row)
		if pageType == "" {
			pageType = strings.Trim(strings.TrimSpace(row.Find(".spp a").First().Text()), "[]【】")
		}

		seen[fullURL] = true
		items = append(items, model.NewsItem{
			Title:       title,
			URL:         fullURL,
			Date:        date,
			PublishedAt: publishedAt,
			Type:        pageType,
			ParsedAt:    time.Now(),
		})
	})

	if len(items) == 0 {
		return nil, fmt.Errorf("bioeng page contains no valid article rows")
	}
	return items, nil
}

func parseBioengHomeLists(lists *goquery.Selection, baseURL string) []model.NewsItem {
	items := make([]model.NewsItem, 0)
	seen := make(map[string]bool)
	lists.Each(func(_ int, list *goquery.Selection) {
		sectionType := bioengSectionTitle(list.Find("h3").First())
		if sectionType == "" {
			return
		}
		list.Find("ul > li").Each(func(_ int, row *goquery.Selection) {
			anchor := row.Find("a[href]").First()
			if anchor.Length() == 0 {
				return
			}
			fullURL, ok := bioengArticleURL(baseURL, anchor.AttrOr("href", ""))
			if !ok || seen[fullURL] {
				return
			}
			title := strings.TrimSpace(anchor.AttrOr("title", ""))
			if title == "" {
				title = strings.TrimSpace(anchor.Text())
			}
			title = cleanTitle(title)
			if title == "" || !isValidNewsTitle(title) || len([]rune(title)) > 160 {
				return
			}
			date := strings.Join(strings.Fields(row.Find("em, time, .date, .time").First().Text()), " ")
			seen[fullURL] = true
			items = append(items, model.NewsItem{
				Title:    title,
				URL:      fullURL,
				Date:     date,
				Type:     sectionType,
				ParsedAt: time.Now(),
			})
		})
	})
	return items
}

func bioengSectionTitle(sel *goquery.Selection) string {
	if sel == nil || sel.Length() == 0 {
		return ""
	}
	clone := sel.Clone()
	clone.Find("a").Remove()
	return strings.Join(strings.Fields(clone.Text()), " ")
}

func bioengRowArticleAnchor(row *goquery.Selection, baseURL string) *goquery.Selection {
	var result *goquery.Selection
	row.Find("a[href]").EachWithBreak(func(_ int, anchor *goquery.Selection) bool {
		if _, ok := bioengArticleURL(baseURL, anchor.AttrOr("href", "")); !ok {
			return true
		}
		// The first link in a live row is often the thumbnail wrapper in
		// <dt>, which has no text or title. Prefer the headline link in
		// <dd>, while retaining the first valid link as a fallback for
		// image-only rows.
		if result == nil {
			result = anchor
		}
		if strings.TrimSpace(anchor.AttrOr("title", "")) != "" || strings.TrimSpace(anchor.Text()) != "" {
			result = anchor
			return false
		}
		return true
	})
	return result
}

func bioengListTitle(anchor *goquery.Selection, fullURL, baseURL string) string {
	title := strings.TrimSpace(anchor.AttrOr("title", ""))
	if title == "" {
		title = strings.TrimSpace(anchor.Text())
	}
	title = cleanTitle(title)

	// The live list component truncates some long titles to a literal "..."
	// and does not provide a title attribute. Repair those rows from their
	// detail page so the feed does not publish a visibly incomplete headline.
	if strings.HasSuffix(title, "...") || strings.HasSuffix(title, "…") {
		if body, err := fetch(fullURL); err == nil {
			if article, err := parseAdapter_bioengArticle(body, baseURL); err == nil && article.Title != "" {
				return strings.TrimSpace(article.Title)
			}
		}
	}
	return title
}

func bioengListDate(row *goquery.Selection) (string, string) {
	if row == nil || row.Length() == 0 {
		return "", ""
	}
	dateText := ""
	for _, selector := range []string{"em", "time", ".date", ".time"} {
		dateText = strings.TrimSpace(row.Find(selector).First().Text())
		if dateText != "" {
			break
		}
	}
	if dateText == "" {
		dateText = strings.TrimSpace(row.Find("dd").First().Text())
	}
	return bioengDateValues(dateText)
}

func bioengDateValues(raw string) (string, string) {
	raw = htmlstd.UnescapeString(strings.Join(strings.Fields(raw), " "))
	if raw == "" {
		return "", ""
	}
	if normalized := normalizePublishedAt(raw); normalized != "" {
		date := normalized[:10]
		if bioengClockRe.MatchString(raw) {
			return date, normalized
		}
		return date, ""
	}
	if match := bioengDateRe.FindStringSubmatch(raw); match != nil {
		return normalizeDateParts(match[1], match[2], match[3]), ""
	}
	return strings.TrimSpace(raw), ""
}

func bioengPageType(doc *goquery.Document) string {
	if doc == nil {
		return ""
	}
	if current := strings.Join(strings.Fields(doc.Find(".main_right .current h3").First().Text()), " "); current != "" {
		return current
	}
	return strings.Join(strings.Fields(doc.Find(`meta[name="pageTitle"]`).AttrOr("content", "")), " ")
}

func bioengArticleURL(baseURL, href string) (string, bool) {
	fullURL := cleanURL(resolveURL(baseURL, strings.TrimSpace(href)))
	parsed, err := url.Parse(fullURL)
	if err != nil || parsed.Host == "" || !bioengArticlePathRe.MatchString(parsed.Path) {
		return "", false
	}
	base, err := url.Parse(baseURL)
	if err != nil || base.Host == "" || !strings.EqualFold(parsed.Host, base.Host) {
		return "", false
	}
	return fullURL, true
}

func parseAdapter_bioengArticle(html []byte, baseURL string) (*model.Article, error) {
	article, err := parseBodaArticle(html, baseURL)
	if err != nil {
		return nil, err
	}
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(html)))
	if err != nil {
		return nil, fmt.Errorf("parse bioeng article: %w", err)
	}

	if pageType := strings.TrimSpace(doc.Find(`meta[name="pageType"]`).AttrOr("content", "")); pageType != "" && pageType != "3" {
		return nil, fmt.Errorf("bioeng page is not an article (pageType %q)", pageType)
	}
	if strings.TrimSpace(article.Title) == "" {
		return nil, fmt.Errorf("bioeng article has no title")
	}
	content := doc.Find(".main_right .content .v_news_content, .content .v_news_content").First()
	if content.Length() == 0 {
		return nil, fmt.Errorf("bioeng article has no content container")
	}
	if strings.TrimSpace(content.Text()) == "" && content.Find("img, table, a").Length() == 0 {
		return nil, fmt.Errorf("bioeng article has empty content")
	}

	if source := doc.Find(".source").First(); source.Length() > 0 {
		fields := bioengMetaFields(flattenedText(source))
		// The source block is authoritative on this site. In particular, an
		// empty source/author must not be filled from unrelated page text.
		article.Source = fields["来源"]
		article.Author = fields["作者"]
		dateValue := fields["日期"]
		if dateValue == "" {
			dateValue = fields["发布时间"]
		}
		if date, publishedAt := bioengDateValues(dateValue); date != "" {
			article.Date = date
			if publishedAt != "" {
				article.PublishedAt = publishedAt
			}
		}
	}
	if typ := bioengPageType(doc); typ != "" {
		article.Type = typ
	}
	appendBioengAttachments(article, doc, baseURL)
	normalizeArticlePublishedAt(article)
	return article, nil
}

func bioengMetaFields(text string) map[string]string {
	text = htmlstd.UnescapeString(strings.Join(strings.Fields(text), " "))
	fields := make(map[string]string)
	matches := bioengMetaLabelRe.FindAllStringSubmatchIndex(text, -1)
	for i, match := range matches {
		if len(match) < 4 {
			continue
		}
		label := text[match[2]:match[3]]
		start := match[1]
		end := len(text)
		if i+1 < len(matches) {
			end = matches[i+1][0]
		}
		value := strings.TrimSpace(text[start:end])
		fields[label] = value
	}
	return fields
}

func appendBioengAttachments(article *model.Article, doc *goquery.Document, baseURL string) {
	if article == nil || doc == nil {
		return
	}
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		seen[attachment.URL] = true
	}

	// Bioeng renders the attachment <ul> after .v_news_content, still inside
	// .article. The generic parser intentionally scopes links to the body and
	// therefore misses this list.
	scope := doc.Find(".main_right .content .article, .article").First()
	if scope.Length() == 0 {
		return
	}
	scope.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		href := strings.TrimSpace(anchor.AttrOr("href", ""))
		lowerHref := strings.ToLower(href)
		if href == "" || !strings.Contains(lowerHref, "download.jsp") || !strings.Contains(lowerHref, "downloadattachurl") {
			return
		}
		name := strings.Join(strings.Fields(htmlstd.UnescapeString(anchor.Text())), " ")
		if name == "" {
			return
		}
		resolved := cleanURL(resolveURL(baseURL, href))
		if seen[resolved] {
			return
		}
		seen[resolved] = true
		article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: resolved})
	})
}
