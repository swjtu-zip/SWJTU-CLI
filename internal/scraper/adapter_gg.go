func init() {
	// The catalogue still carries the historical HTTP value. The live site
	// serves the same content over HTTP, but HTTPS is the canonical base and
	// is also what should be used when resolving article/image URLs.
	if site := AllSites["gg"]; site != nil {
		site.BaseURL = ggBaseURL
	}
	registerAdapter("gg", SiteAdapter{
		SubPages:     ggSubPages,
		ParseList:    parseAdapter_ggList,
		ParseArticle: parseAdapter_ggArticle,
		PageURL:      ggPageURL,
	})
}

// ggPageURL maps the logical page number (1=newest) to the reverse-numbered
// static files generated by the live site. For example, a 26-page list has
// page 2 at /25.htm and page 26 at /1.htm.
func ggPageURL(baseURL, slug string, page, totalPages int, extension string) string {
	baseURL = strings.TrimRight(strings.TrimSpace(baseURL), "/")
	slug = strings.Trim(slug, "/")
	if extension == "" {
		extension = ".htm"
	} else if !strings.HasPrefix(extension, ".") {
		extension = "." + extension
	}
	if baseURL == "" || slug == "" || page < 1 {
		return ""
	}
	if page == 1 {
		return fmt.Sprintf("%s/%s%s", baseURL, slug, extension)
	}
	if totalPages < 1 || page > totalPages {
		return ""
	}
	filePage := totalPages - page + 1
	if filePage < 1 {
		return ""
	}
	return fmt.Sprintf("%s/%s/%d%s", baseURL, slug, filePage, extension)
}

func parseAdapter_ggList(html []byte, baseURL string) ([]model.NewsItem, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(html)))
	if err != nil {
		return nil, fmt.Errorf("parse gg list: %w", err)
	}

	// Every actual GG list page, including an empty list, has this container.
	// Restricting extraction to it prevents side menus, profile directories,
	// footer links, and external links from becoming fake news rows.
	if list := doc.Find(".list-col .list-list").First(); list.Length() > 0 {
		if pageType := ggPageType(doc); pageType != "" && pageType != "2" {
			return nil, fmt.Errorf("gg: unexpected list page type %q", pageType)
		}
		return ggParseListRows(list, ggListType(doc), baseURL), nil
	}

	if ggHasHomeLayout(doc) {
		items := ggParseHome(doc, baseURL)
		if len(items) == 0 {
			return nil, fmt.Errorf("gg: homepage contains no article entries")
		}
		return items, nil
	}

	return nil, fmt.Errorf("gg: response is not a homepage or list page")
}

func ggParseListRows(list *goquery.Selection, itemType, baseURL string) []model.NewsItem {
	rows := list.ChildrenFiltered("ul").First().ChildrenFiltered("li")
	if rows.Length() == 0 {
		rows = list.ChildrenFiltered("li")
	}

	items := make([]model.NewsItem, 0, rows.Length())
	seen := make(map[string]bool, rows.Length())
	rows.Each(func(_ int, row *goquery.Selection) {
		anchor := row.Find("a[href]").First()
		if anchor.Length() == 0 {
			return
		}
		fullURL, ok := ggArticleURL(baseURL, anchor.AttrOr("href", ""))
		if !ok || seen[fullURL] {
			return
		}

		title := strings.TrimSpace(anchor.AttrOr("title", ""))
		if title == "" {
			clone := anchor.Clone()
			clone.Find("i, .date, .time, time").Remove()
			title = strings.TrimSpace(clone.Text())
		}
		if title == "" || !isValidNewsTitle(title) {
			return
		}

		dateSource := row.Find("i, time, .date, .time").First().Text()
		if dateSource == "" {
			dateSource = row.Text()
		}
		date, publishedAt := ggDateValues(dateSource)
		seen[fullURL] = true
		items = append(items, model.NewsItem{
			Title:       title,
			URL:         fullURL,
			Date:        date,
			PublishedAt: publishedAt,
			Type:        itemType,
			ParsedAt:    time.Now(),
		})
	})
	return items
}

type ggHomeSection struct {
	selector string
	itemType string
}

func ggHasHomeLayout(doc *goquery.Document) bool {
	for _, section := range []ggHomeSection{
		{selector: ".news-fl", itemType: "学院新闻"},
		{selector: ".notice", itemType: "通知公告"},
		{selector: ".science", itemType: "学术科研"},
		{selector: ".teach", itemType: "教学信息"},
	} {
		if doc.Find(section.selector).Length() == 0 {
			return false
		}
	}
	return true
}

func ggParseHome(doc *goquery.Document, baseURL string) []model.NewsItem {
	items := make([]model.NewsItem, 0)
	seen := make(map[string]int)
	sections := []ggHomeSection{
		{selector: ".news-fl", itemType: "学院新闻"},
		{selector: ".notice", itemType: "通知公告"},
		{selector: ".science", itemType: "学术科研"},
		{selector: ".teach", itemType: "教学信息"},
	}

	for _, section := range sections {
		sectionSel := doc.Find(section.selector).First()
		if section.selector == ".news-fl" {
			sectionSel.Find(".news-imgs a[href]").Each(func(_ int, anchor *goquery.Selection) {
				ggAddHomeItem(&items, seen, anchor, nil, section.itemType, baseURL)
			})
		}
		list := sectionSel.Find("ul").First()
		list.ChildrenFiltered("li").Each(func(_ int, row *goquery.Selection) {
			ggAddHomeItem(&items, seen, row.Find("a[href]").First(), row, section.itemType, baseURL)
		})
	}
	return items
}

func ggAddHomeItem(items *[]model.NewsItem, seen map[string]int, anchor, row *goquery.Selection, itemType, baseURL string) {
	if anchor == nil || anchor.Length() == 0 {
		return
	}
	fullURL, ok := ggArticleURL(baseURL, anchor.AttrOr("href", ""))
	if !ok {
		return
	}

	title := strings.TrimSpace(anchor.AttrOr("title", ""))
	if title == "" {
		title = strings.TrimSpace(anchor.Find("img").First().AttrOr("alt", ""))
	}
	if title == "" {
		title = strings.TrimSpace(anchor.Find("p b, p").First().Text())
	}
	if title == "" {
		clone := anchor.Clone()
		clone.Find("i, .date, .time, time").Remove()
		title = strings.TrimSpace(clone.Text())
	}
	if title == "" || !isValidNewsTitle(title) {
		return
	}

	dateSource := ""
	if row != nil {
		dateSource = row.Find("i, time, .date, .time").First().Text()
		if dateSource == "" {
			// The 学院新闻 rows put the date in plain text brackets rather
			// than an element; the date regex safely ignores the title text.
			dateSource = row.Text()
		}
	}
	date, publishedAt := ggDateValues(dateSource)
	item := model.NewsItem{
		Title:       title,
		URL:         fullURL,
		Date:        date,
		PublishedAt: publishedAt,
		Type:        itemType,
		ParsedAt:    time.Now(),
	}

	if index, exists := seen[fullURL]; exists {
		// The featured card and the corresponding news-list row share a URL;
		// keep one item while allowing the row's complete title/date to fill a
		// card's abbreviated or date-less presentation.
		if item.Title != "" && (strings.Contains((*items)[index].Title, "…") || strings.Contains((*items)[index].Title, "...")) {
			(*items)[index].Title = item.Title
		}
		if (*items)[index].Date == "" && item.Date != "" {
			(*items)[index].Date = item.Date
			(*items)[index].PublishedAt = item.PublishedAt
		}
		return
	}
	seen[fullURL] = len(*items)
	*items = append(*items, item)
}

func parseAdapter_ggArticle(html []byte, baseURL string) (*model.Article, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(html)))
	if err != nil {
		return nil, fmt.Errorf("parse gg article: %w", err)
	}
	if !ggHasArticleLayout(doc) {
		return nil, fmt.Errorf("gg: response is not a detail article")
	}

	article, err := parseBodaArticle(html, baseURL)
	if err != nil {
		return nil, fmt.Errorf("parse gg article: %w", err)
	}
	if strings.TrimSpace(article.Title) == "" {
		return nil, fmt.Errorf("gg: article has no title")
	}

	article.Type = ggListType(doc)
	dateSource := doc.Find(".article .source").First().Text()
	date, publishedAt := ggDateValues(dateSource)
	if date == "" {
		date, publishedAt = ggDateValues(article.Date)
	}
	if date != "" {
		article.Date = date
	}
	// parseBodaArticle's generic normalizer can infer a midnight timestamp from
	// date-only input. GG only exposes PublishedAt when the source has a clock.
	article.PublishedAt = publishedAt
	ggCollectAttachments(doc, baseURL, article)
	return article, nil
}

func ggHasArticleLayout(doc *goquery.Document) bool {
	if ggPageType(doc) != "3" {
		return false
	}
	article := doc.Find(".article").First()
	return article.Length() > 0 && article.Find("h1").Length() > 0 && article.Find(".v_news_content").Length() > 0
}

func ggCollectAttachments(doc *goquery.Document, baseURL string, article *model.Article) {
	attachments := make([]model.Attachment, 0, len(article.Attachments))
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		if !ggSameHostURL(attachment.URL, baseURL) {
			continue
		}
		attachments = append(attachments, attachment)
		seen[attachment.URL] = true
	}
	article.Attachments = attachments

	doc.Find(".article a[href]").Each(func(_ int, anchor *goquery.Selection) {
		href := strings.TrimSpace(anchor.AttrOr("href", ""))
		if !ggLooksLikeAttachment(anchor, href) {
			return
		}
		name := strings.TrimSpace(anchor.Text())
		if name == "" {
			name = strings.TrimSpace(anchor.AttrOr("download", ""))
		}
		if name == "" {
			return
		}
		resolved := resolveURL(baseURL, href)
		if !ggSameHostURL(resolved, baseURL) {
			return
		}
		if seen[resolved] {
			return
		}
		seen[resolved] = true
		article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: resolved})
	})
}

func ggLooksLikeAttachment(anchor *goquery.Selection, href string) bool {
	lowerHref := strings.ToLower(href)
	if strings.Contains(lowerHref, "download.jsp") || anchor.AttrOr("download", "") != "" {
		return true
	}
	for _, extension := range ggAttachmentExtensions {
		if strings.Contains(lowerHref, extension) {
			return true
		}
	}
	return false
}

func ggArticleURL(baseURL, href string) (string, bool) {
	fullURL := cleanURL(resolveURL(baseURL, strings.TrimSpace(href)))
	parsed, err := url.Parse(fullURL)
	if err != nil || !ggSameHostURL(fullURL, baseURL) || !ggArticlePathRE.MatchString(parsed.Path) || !isValidNewsURL(fullURL) {
		return "", false
	}
	return fullURL, true
}

func ggSameHostURL(raw, baseURL string) bool {
	parsed, err := url.Parse(raw)
	if err != nil || parsed.Host == "" {
		return false
	}
	base, err := url.Parse(baseURL)
	if err != nil || base.Host == "" || !strings.EqualFold(parsed.Host, base.Host) {
		return false
	}
	return true
}

func ggListType(doc *goquery.Document) string {
	return strings.Join(strings.Fields(doc.Find(".list-col > h4").First().Text()), " ")
}

func ggPageType(doc *goquery.Document) string {
	if value := doc.Find(`meta[name="pageType"]`).First().AttrOr("content", ""); value != "" {
		return strings.TrimSpace(value)
	}
	return strings.TrimSpace(doc.Find(`meta[name="pagetype"]`).First().AttrOr("content", ""))
}

// ggDateValues returns a backwards-compatible calendar Date and a precise
// PublishedAt only when the source contains a time-of-day.
func ggDateValues(value string) (date, publishedAt string) {
	value = strings.Join(strings.Fields(strings.ReplaceAll(value, "\u00a0", " ")), " ")
	if match := ggDateTimeRE.FindStringSubmatch(value); match != nil {
		date = normalizeDateParts(match[1], match[2], match[3])
		if date == "" {
			return "", ""
		}
		second := match[6]
		if second == "" {
			second = "00"
		}
		hour := match[4]
		if len(hour) == 1 {
			hour = "0" + hour
		}
		return date, fmt.Sprintf("%s %s:%s:%s", date, hour, match[5], second)
	}
	if match := ggDateRE.FindStringSubmatch(value); match != nil {
		return normalizeDateParts(match[1], match[2], match[3]), ""
	}
	return "", ""
}
