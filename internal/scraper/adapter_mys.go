func init() {
	// The registry entry predates the HTTPS canonical URL.  Keep all emitted
	// article/resource URLs on the HTTPS origin even when the caller passes the
	// historical HTTP base URL.
	if site := AllSites["mys"]; site != nil {
		site.BaseURL = mysCanonicalBaseURL
	}
	registerAdapter("mys", SiteAdapter{
		SubPages:     mysSubPages,
		ParseList:    parseAdapter_mysList,
		ParseArticle: parseAdapter_mysArticle,
		PageURL:      mysPageURL,
		TotalPages:   mysTotalPages,
	})
}

// mysPageURL maps the logical page number (1=newest) to the reverse-numbered
// files generated by Visual SiteBuilder.  For example, xyt advertises 58
// pages, so logical page 2 is /xyt/57.htm and logical page 58 is /xyt/1.htm.
func mysPageURL(baseURL, slug string, page, totalPages int, extension string) string {
	baseURL = mysCanonicalBase(baseURL)
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	if extension == "" {
		extension = ".htm"
	} else if !strings.HasPrefix(extension, ".") {
		extension = "." + extension
	}
	if page < 1 || (page > 1 && totalPages < 1) || (totalPages > 0 && page > totalPages) {
		return ""
	}
	if page == 1 {
		return fmt.Sprintf("%s/%s%s", baseURL, slug, extension)
	}
	physical := totalPages - page + 1
	return fmt.Sprintf("%s/%s/%d%s", baseURL, slug, physical, extension)
}

func mysTotalPages(slug string) (int, error) {
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	if !mysKnownFeed(slug) {
		return 0, fmt.Errorf("mys: %q is not an article-list route", slug)
	}
	body, err := fetch(mysPageURL(mysCanonicalBaseURL, slug, 1, 0, ".htm"))
	if err != nil {
		return 0, fmt.Errorf("mys: fetch first page for %s: %w", slug, err)
	}
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(body)))
	if err != nil {
		return 0, fmt.Errorf("mys: parse first page for %s: %w", slug, err)
	}
	if mysPageType(doc) == "3" {
		return 0, fmt.Errorf("mys: %s is an article, not a list", slug)
	}
	if doc.Find(".news-list-box ul.list").First().Length() == 0 {
		return 0, fmt.Errorf("mys: %s is not an article list", slug)
	}
	pages := mysPageCount(body)
	if pages < 1 {
		return 0, fmt.Errorf("mys: %s has no reliable page count", slug)
	}
	return pages, nil
}

func mysKnownFeed(slug string) bool {
	for _, known := range mysSubPages {
		if slug == known {
			return true
		}
	}
	return false
}

func mysPageCount(raw []byte) int {
	maxPage := 0
	for _, match := range mysPageCountRE.FindAllSubmatch(raw, -1) {
		if len(match) != 2 {
			continue
		}
		var page int
		if _, err := fmt.Sscanf(string(match[1]), "%d", &page); err == nil && page > maxPage {
			maxPage = page
		}
	}
	return maxPage
}

func parseAdapter_mysList(raw []byte, baseURL string) ([]model.NewsItem, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("mys: parse list HTML: %w", err)
	}
	pageType := mysPageType(doc)
	if pageType == "3" {
		return nil, fmt.Errorf("mys: article page supplied to list parser")
	}

	baseURL = mysCanonicalBase(baseURL)
	if pageType == "1" {
		items := mysHomepageItems(doc, baseURL)
		if len(items) == 0 {
			return nil, fmt.Errorf("mys: homepage contains no article modules")
		}
		return items, nil
	}

	list := doc.Find(".news-list-box ul.list").First()
	if list.Length() == 0 {
		return nil, fmt.Errorf("mys: response is a static/service page, not an article list")
	}
	if pageType != "" && pageType != "2" {
		return nil, fmt.Errorf("mys: unsupported pageType %q", pageType)
	}

	items := make([]model.NewsItem, 0)
	seen := make(map[string]bool)
	pageTypeName := mysListType(doc)
	rows := list.ChildrenFiltered("li")
	if rows.Length() == 0 {
		rows = list.Find("li")
	}
	rows.Each(func(_ int, row *goquery.Selection) {
		mysAppendListRow(&items, seen, row, pageTypeName, baseURL)
	})
	return items, nil
}

func mysHomepageItems(doc *goquery.Document, baseURL string) []model.NewsItem {
	items := make([]model.NewsItem, 0)
	seen := make(map[string]int)

	// The carousel is a real article module, even though it has no category or
	// date in the homepage markup.  Do not invent either field; a later list
	// module may fill them when the same URL is repeated.
	doc.Find(".banner .swiper-wrapper > li").Each(func(_ int, row *goquery.Selection) {
		mysAppendHomepageRow(&items, seen, row, "", baseURL)
	})

	// All four current news modules are rendered in the HTML, including the
	// modules hidden by CSS/JavaScript on a narrow viewport.  The module h4 is
	// the source's own type label for these homepage rows.
	doc.Find(".news-list > .item").Each(func(_ int, box *goquery.Selection) {
		itemType := mysCleanText(box.Find(".title h4").First().Text())
		box.Find("ul.list > li").Each(func(_ int, row *goquery.Selection) {
			mysAppendHomepageRow(&items, seen, row, itemType, baseURL)
		})
	})
	return items
}

func mysAppendHomepageRow(items *[]model.NewsItem, seen map[string]int, row *goquery.Selection, itemType, baseURL string) {
	anchor := row.Find("a[href]").First()
	if anchor.Length() == 0 {
		return
	}
	fullURL, ok := mysArticleURL(baseURL, anchor.AttrOr("href", ""))
	if !ok {
		return
	}
	title := mysRowTitle(row)
	date, publishedAt := mysRowDate(row)
	itemType = mysCleanText(itemType)
	if title == "" {
		return
	}
	if index, exists := seen[fullURL]; exists {
		// Prefer a complete list title/date/type over a display-only carousel
		// entry if a homepage article is repeated in another module.
		if mysTitleIsTruncated((*items)[index].Title) && !mysTitleIsTruncated(title) {
			(*items)[index].Title = title
		}
		if (*items)[index].Date == "" && date != "" {
			(*items)[index].Date = date
			(*items)[index].PublishedAt = publishedAt
		}
		if (*items)[index].Type == "" && itemType != "" {
			(*items)[index].Type = itemType
		}
		return
	}
	seen[fullURL] = len(*items)
	*items = append(*items, model.NewsItem{
		Title:       title,
		URL:         fullURL,
		Date:        date,
		PublishedAt: publishedAt,
		Type:        itemType,
		ParsedAt:    time.Now(),
	})
}

func mysAppendListRow(items *[]model.NewsItem, seen map[string]bool, row *goquery.Selection, fallbackType, baseURL string) {
	anchor := row.Find("a[href]").First()
	if anchor.Length() == 0 {
		return
	}
	fullURL, ok := mysArticleURL(baseURL, anchor.AttrOr("href", ""))
	if !ok || seen[fullURL] {
		return
	}
	title := mysRowTitle(row)
	if title == "" {
		return
	}
	// In the current template the type is a direct child span of .desc.  Do
	// not use the first descendant span: the duplicate-tag variant puts the
	// row date in that nested position, which would turn the date into Type.
	typ := ""
	row.Find(".desc > span").EachWithBreak(func(_ int, candidate *goquery.Selection) bool {
		value := mysCleanText(candidate.Text())
		if value == "" {
			return true
		}
		if date, _ := mysDateValues(value); date != "" {
			return true
		}
		typ = value
		return false
	})
	if typ == "" {
		typ = mysCleanText(fallbackType)
	}
	date, publishedAt := mysRowDate(row)
	seen[fullURL] = true
	*items = append(*items, model.NewsItem{
		Title:       title,
		URL:         fullURL,
		Date:        date,
		PublishedAt: publishedAt,
		Type:        typ,
		ParsedAt:    time.Now(),
	})
}

func mysRowTitle(row *goquery.Selection) string {
	if row == nil || row.Length() == 0 {
		return ""
	}
	if desc := row.Find(".desc").First(); desc.Length() > 0 {
		clone := desc.Clone()
		clone.Find("span").First().Remove()
		if title := mysCleanText(clone.Text()); title != "" {
			return title
		}
	}
	anchor := row.Find("a[href]").First()
	if anchor.Length() == 0 {
		return ""
	}
	clone := anchor.Clone()
	clone.Find(".state, .date, .time, time").Remove()
	if title := mysCleanText(clone.Text()); title != "" {
		return title
	}
	return mysCleanText(anchor.AttrOr("title", ""))
}

func mysRowDate(row *goquery.Selection) (string, string) {
	if row == nil || row.Length() == 0 {
		return "", ""
	}
	raw := row.Find(".state, .date, .time, time").First().Text()
	if raw == "" {
		raw = row.Text()
	}
	return mysDateValues(raw)
}

func mysDateValues(raw string) (string, string) {
	raw = htmlstd.UnescapeString(strings.Join(strings.Fields(raw), " "))
	if raw == "" {
		return "", ""
	}
	if publishedAt := normalizePublishedAt(raw); publishedAt != "" {
		date := publishedAt[:10]
		if strings.Contains(publishedAt, ":") {
			return date, publishedAt
		}
		return date, ""
	}
	return "", ""
}

func parseAdapter_mysArticle(raw []byte, baseURL string) (*model.Article, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("mys: parse article HTML: %w", err)
	}
	if pageType := mysPageType(doc); pageType != "3" {
		return nil, fmt.Errorf("mys: response is not an article (pageType %q)", pageType)
	}

	baseURL = mysCanonicalBase(baseURL)
	article, err := parseBodaArticle(raw, baseURL)
	if err != nil {
		return nil, fmt.Errorf("mys: parse common article fields: %w", err)
	}
	article.Title = mysArticleTitle(doc)
	if article.Title == "" {
		return nil, fmt.Errorf("mys: article has no detail-page title")
	}
	if typ := mysArticleType(doc); typ != "" {
		article.Type = typ
	}

	content := doc.Find(".detail-box .v_news_content").First()
	if content.Length() == 0 {
		return nil, fmt.Errorf("mys: article has no .v_news_content container")
	}
	if strings.TrimSpace(content.Text()) == "" && content.Find("img, a, table").Length() == 0 {
		return nil, fmt.Errorf("mys: article has empty content")
	}
	if strings.TrimSpace(article.Content) == "" {
		clone := content.Clone()
		clone.Find("script, style, noscript").Remove()
		article.Content = mysCleanText(clone.Text())
	}

	mysAppendAttachments(article, doc, baseURL)
	normalizeArticlePublishedAt(article)
	return article, nil
}

// mysPageType tolerates duplicate CMS meta tags.  Some live detail responses
// include a shell tag for the surrounding page in addition to the detail tag;
// the DOM shape is the authority in that case, not the first meta element.
func mysPageType(doc *goquery.Document) string {
	if doc == nil {
		return ""
	}
	values := make([]string, 0)
	doc.Find(`meta[name="pageType"], meta[name="pagetype"]`).Each(func(_ int, meta *goquery.Selection) {
		if value := strings.TrimSpace(meta.AttrOr("content", "")); value != "" {
			values = append(values, value)
		}
	})
	if doc.Find(".detail-box .v_news_content, .detail-box").Length() > 0 {
		for _, value := range values {
			if value == "3" {
				return value
			}
		}
	}
	if doc.Find(".news-list-box ul.list").Length() > 0 {
		for _, value := range values {
			if value == "2" {
				return value
			}
		}
	}
	if doc.Find(".banner .swiper-wrapper, .news-list").Length() > 0 {
		for _, value := range values {
			if value == "1" {
				return value
			}
		}
	}
	if len(values) > 0 {
		return values[0]
	}
	return ""
}

func mysArticleTitle(doc *goquery.Document) string {
	// A live detail response can retain the homepage shell's pageTitle meta
	// before the detail-page meta.  The rendered detail heading is authoritative
	// for the article title.
	if title := mysCleanText(doc.Find(".detail-box .hd h3, .detail-box h3").First().Text()); title != "" {
		return title
	}
	return mysCleanText(doc.Find(`meta[name="pageTitle"]`).Last().AttrOr("content", ""))
}

func mysListType(doc *goquery.Document) string {
	return mysCleanText(doc.Find(".news-list-box .title h4").First().Text())
}

func mysArticleType(doc *goquery.Document) string {
	if typ := mysListType(doc); typ != "" && typ != "正文" {
		return typ
	}
	var result string
	doc.Find(".crumbs-nav a").Each(func(_ int, anchor *goquery.Selection) {
		value := mysCleanText(anchor.Text())
		if value == "" || value == "首页" || value == "正文" || value == ">" {
			return
		}
		result = strings.TrimRight(value, ">")
	})
	return strings.TrimSpace(result)
}

func mysAppendAttachments(article *model.Article, doc *goquery.Document, baseURL string) {
	if article == nil || doc == nil {
		return
	}
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		seen[attachment.URL] = true
	}
	scope := doc.Find(".detail-box").First()
	if scope.Length() == 0 {
		scope = doc.Selection
	}
	scope.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		href := strings.TrimSpace(anchor.AttrOr("href", ""))
		if href == "" || strings.HasPrefix(strings.ToLower(href), "javascript:") {
			return
		}
		name := mysCleanText(anchor.Text())
		if name == "" {
			name = mysCleanText(anchor.AttrOr("download", ""))
		}
		rowText := ""
		if parent := anchor.Closest("li"); parent.Length() > 0 {
			rowText = mysCleanText(parent.Text())
		}
		lowerHref := strings.ToLower(href)
		labeled := strings.Contains(rowText, "附件")
		isDownload := strings.Contains(lowerHref, "download.jsp")
		isFile := mysAttachmentRE.MatchString(href)
		if name == "" || (!labeled && !isDownload && !isFile) {
			return
		}
		resolved := resolveURL(baseURL, href)
		if seen[resolved] {
			return
		}
		seen[resolved] = true
		article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: resolved})
	})
}

func mysArticleURL(baseURL, href string) (string, bool) {
	fullURL := cleanURL(resolveURL(mysCanonicalBase(baseURL), strings.TrimSpace(href)))
	parsed, err := url.Parse(fullURL)
	if err != nil || parsed.Host == "" || !mysArticlePathRE.MatchString(parsed.Path) {
		return "", false
	}
	base, err := url.Parse(mysCanonicalBase(baseURL))
	if err != nil || !strings.EqualFold(parsed.Hostname(), base.Hostname()) {
		return "", false
	}
	return fullURL, true
}

func mysCanonicalBase(raw string) string {
	parsed, err := url.Parse(strings.TrimSpace(raw))
	if err == nil && strings.EqualFold(parsed.Hostname(), "mys.swjtu.edu.cn") {
		return mysCanonicalBaseURL
	}
	return strings.TrimRight(strings.TrimSpace(raw), "/")
}

func mysCleanText(value string) string {
	return strings.Join(strings.Fields(htmlstd.UnescapeString(value)), " ")
}

func mysTitleIsTruncated(title string) bool {
	return strings.HasSuffix(strings.TrimSpace(title), "...") || strings.HasSuffix(strings.TrimSpace(title), "…")
}
