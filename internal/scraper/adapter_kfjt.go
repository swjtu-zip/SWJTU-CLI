const kfjtCanonicalBaseURL = "https://kfjt.swjtu.edu.cn"

// kfjtSubPages contains the article-bearing routes discovered in the site's
// navigation and homepage tabs.  Landing pages such as 集团简介、组织架构、
// 部门职责、企业文化 and 监督举报 are intentionally not feeds.
var kfjtSubPages = []string{
	"xwzx/xwdt",
	"xwzx/tzgg",
	"djgz/djdt",
	"djgz/zbdj",
	"djgz/lxjc",
	"jjgz/jjdt",
	"jjgz/djfg",
	"jjgz/jsjy",
	"qywh/qydt",
	"qywh/whjs",
	"zcfg",
	"tzqy/qyjs",
}

var (
	kfjtArticlePathRE = regexp.MustCompile(`(?i)^/info/[0-9]+/[0-9]+\.html?$`)
	kfjtDateTimeRE    = regexp.MustCompile(`(?i)([0-9]{2,4})\s*(?:年|[-/.])\s*([0-9]{1,2})\s*(?:月|[-/.])\s*([0-9]{1,2})\s*(?:日|号)?\s*(?:[Tt]|\s+)\s*([0-9]{1,2})\s*[:：]\s*([0-9]{2})(?:\s*[:：]\s*([0-9]{2}))?`)
	kfjtDateRE        = regexp.MustCompile(`(?i)([0-9]{2,4})\s*(?:年|[-/.])\s*([0-9]{1,2})\s*(?:月|[-/.])\s*([0-9]{1,2})\s*(?:日|号)?`)
	kfjtAttachmentRE  = regexp.MustCompile(`(?i)\.(?:pdf|docx?|xlsx?|pptx?|zip|rar|7z|txt|csv|wps|rtf)(?:$|[?#&])`)
)

func init() {
	if site := AllSites["kfjt"]; site != nil {
		site.BaseURL = kfjtCanonicalBaseURL
	}
	registerAdapter("kfjt", SiteAdapter{
		SubPages:     kfjtSubPages,
		ParseList:    parseAdapter_kfjtList,
		ParseArticle: parseAdapter_kfjtArticle,
		PageURL:      kfjtPageURL,
		TotalPages:   kfjtTotalPages,
	})
}

// kfjtPageURL maps the logical page number (1 = newest) to the reverse-numbered
// files generated by the site. For a 14-page list, logical page 2 is /13.htm
// and logical page 14 is /1.htm.
func kfjtPageURL(baseURL, slug string, page, totalPages int, extension string) string {
	baseURL = kfjtCanonicalBase(baseURL)
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	if extension == "" {
		extension = ".htm"
	} else if !strings.HasPrefix(extension, ".") {
		extension = "." + extension
	}
	if slug == "" || slug == "index" || slug == "home" {
		return baseURL + "/index" + extension
	}
	if page <= 1 || totalPages <= 1 {
		return fmt.Sprintf("%s/%s%s", baseURL, slug, extension)
	}
	physical := totalPages - page + 1
	if physical < 1 {
		physical = 1
	}
	return fmt.Sprintf("%s/%s/%d%s", baseURL, slug, physical, extension)
}

func kfjtKnownFeed(slug string) bool {
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	for _, known := range kfjtSubPages {
		if slug == known {
			return true
		}
	}
	return false
}

func kfjtTotalPages(slug string) (int, error) {
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	if !kfjtKnownFeed(slug) {
		return 0, fmt.Errorf("kfjt: %q is not an article-list route", slug)
	}
	body, err := fetch(kfjtPageURL(kfjtCanonicalBaseURL, slug, 1, 0, ".htm"))
	if err != nil {
		return 0, fmt.Errorf("kfjt: fetch first page for %s: %w", slug, err)
	}
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(body)))
	if err != nil {
		return 0, fmt.Errorf("kfjt: parse first page for %s: %w", slug, err)
	}
	if err := kfjtRejectPage(doc, "list"); err != nil {
		return 0, err
	}
	if doc.Find(".main .right .list").First().Length() == 0 {
		return 0, fmt.Errorf("kfjt: %s is not an article list", slug)
	}
	return kfjtPaginationTotal(doc), nil
}

func parseAdapter_kfjtList(raw []byte, baseURL string) ([]model.NewsItem, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("kfjt: parse list HTML: %w", err)
	}
	if err := kfjtRejectPage(doc, "list"); err != nil {
		return nil, err
	}
	baseURL = kfjtCanonicalBase(baseURL)
	if kfjtIsHomepage(doc) {
		items := kfjtHomepageItems(doc, baseURL)
		if len(items) == 0 {
			return nil, fmt.Errorf("kfjt: homepage contains no local article modules")
		}
		return items, nil
	}
	if kfjtPageType(doc) != "2" {
		return nil, fmt.Errorf("kfjt: response is not an article list")
	}
	list := doc.Find(".main .right .list").First()
	if list.Length() == 0 {
		return nil, fmt.Errorf("kfjt: response is a static/service page, not an article list")
	}

	items := make([]model.NewsItem, 0)
	seen := make(map[string]bool)
	itemType := kfjtListType(doc)
	rows := list.Find("ul").First().ChildrenFiltered("li")
	if rows.Length() == 0 {
		rows = list.Find("li")
	}
	rows.Each(func(_ int, row *goquery.Selection) {
		kfjtAppendListRow(&items, seen, row, itemType, baseURL)
	})
	return items, nil
}

func kfjtHomepageItems(doc *goquery.Document, baseURL string) []model.NewsItem {
	items := make([]model.NewsItem, 0)
	seen := make(map[string]int)

	// Every tab panel is present in the HTML, including panels hidden by the
	// site's JavaScript. Pair panels with the corresponding tab labels by DOM
	// order so hidden 通知公告 and 纪检动态 are not lost.
	doc.Find(".news-wrap .news-box").Each(func(_ int, box *goquery.Selection) {
		tabs := box.Find(".tabs a")
		panels := box.Find(".bd .item")
		panels.Each(func(index int, panel *goquery.Selection) {
			itemType := ""
			if index < tabs.Length() {
				itemType = strings.Join(strings.Fields(tabs.Eq(index).Text()), " ")
			}
			panel.Find("li").Each(func(_ int, row *goquery.Selection) {
				kfjtAppendHomeRow(&items, seen, row, itemType, baseURL)
			})
		})
	})

	// The hero carousel is another homepage module. It mostly duplicates the
	// news tab, but retain any local article that is only present there and use
	// the tab metadata when a URL is duplicated.
	doc.Find(".news-swiper li").Each(func(_ int, row *goquery.Selection) {
		kfjtAppendHomeRow(&items, seen, row, "新闻动态", baseURL)
	})
	return items
}

func kfjtAppendHomeRow(items *[]model.NewsItem, seen map[string]int, row *goquery.Selection, itemType, baseURL string) {
	anchor := row.Find("a[href]").First()
	if anchor.Length() == 0 {
		return
	}
	title := kfjtRowTitle(anchor)
	dateSource := row.Find(".time, .date, time").First().Text()
	if dateSource == "" {
		dateSource = row.Text()
	}
	date, publishedAt := kfjtDateValues(dateSource)
	kfjtAppendItem(items, seen, anchor.AttrOr("href", ""), title, date, publishedAt, itemType, baseURL)
}

func kfjtAppendListRow(items *[]model.NewsItem, seen map[string]bool, row *goquery.Selection, itemType, baseURL string) {
	anchor := row.Find("a[href]").First()
	if anchor.Length() == 0 {
		return
	}
	title := kfjtRowTitle(anchor)
	date, publishedAt := kfjtDateValues(row.Find(".time, .date, time").First().Text())
	fullURL, ok := kfjtArticleURL(baseURL, anchor.AttrOr("href", ""))
	if !ok || seen[fullURL] || !kfjtValidTitle(title) {
		return
	}
	seen[fullURL] = true
	*items = append(*items, model.NewsItem{
		Title:       title,
		URL:         fullURL,
		Date:        date,
		PublishedAt: publishedAt,
		Type:        strings.TrimSpace(itemType),
		ParsedAt:    time.Now(),
	})
}

func kfjtAppendItem(items *[]model.NewsItem, seen map[string]int, href, title, date, publishedAt, itemType, baseURL string) {
	fullURL, ok := kfjtArticleURL(baseURL, href)
	if !ok || !kfjtValidTitle(title) {
		return
	}
	title = strings.TrimSpace(title)
	itemType = strings.TrimSpace(itemType)
	if index, exists := seen[fullURL]; exists {
		// Carousel cards and tab rows duplicate URLs. Prefer the tab's complete
		// title/date over a display-only card with omitted metadata.
		if (*items)[index].Date == "" && date != "" {
			(*items)[index].Date = date
			(*items)[index].PublishedAt = publishedAt
		}
		if (strings.Contains((*items)[index].Title, "...") || strings.Contains((*items)[index].Title, "…")) && title != "" {
			(*items)[index].Title = title
		}
		if (*items)[index].Type == "" && itemType != "" {
			(*items)[index].Type = itemType
		}
		return
	}
	seen[fullURL] = len(*items)
	*items = append(*items, model.NewsItem{
		Title:       title,
		URL:         fullURL,
		Date:        date,
		PublishedAt: publishedAt,
		Type:        itemType,
		ParsedAt:    time.Now(),
	})
}

func kfjtRowTitle(anchor *goquery.Selection) string {
	if title := strings.TrimSpace(anchor.AttrOr("title", "")); title != "" {
		return title
	}
	for _, selector := range []string{".title", ".toe", "p"} {
		if sel := anchor.Find(selector).First(); sel.Length() > 0 {
			if title := strings.TrimSpace(sel.Text()); title != "" {
				return title
			}
		}
	}
	clone := anchor.Clone()
	clone.Find(".time, .date, time, .desc, img").Remove()
	return strings.Join(strings.Fields(clone.Text()), " ")
}

func kfjtValidTitle(title string) bool {
	title = strings.Join(strings.Fields(strings.TrimSpace(title)), " ")
	if len([]rune(title)) < 2 {
		return false
	}
	switch title {
	case "首页", "更多", "新闻中心", "新闻动态", "通知公告", "党建动态", "纪检动态", "企业动态", "政策法规", "企业介绍":
		return false
	default:
		return true
	}
}

func parseAdapter_kfjtArticle(raw []byte, baseURL string) (*model.Article, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("kfjt: parse article HTML: %w", err)
	}
	if err := kfjtRejectPage(doc, "article"); err != nil {
		return nil, err
	}
	if kfjtPageType(doc) != "3" {
		return nil, fmt.Errorf("kfjt: response is not an article page")
	}
	shell := doc.Find(".detail").First()
	if shell.Length() == 0 {
		return nil, fmt.Errorf("kfjt: article shell is missing")
	}
	title := strings.Join(strings.Fields(shell.Find(".hd h3").First().Text()), " ")
	if !kfjtValidTitle(title) {
		return nil, fmt.Errorf("kfjt: article title is missing")
	}
	if shell.Find(".v_news_content").First().Length() == 0 {
		return nil, fmt.Errorf("kfjt: article content shell is missing")
	}

	baseURL = kfjtCanonicalBase(baseURL)
	article, err := parseBodaArticle(raw, baseURL)
	if err != nil {
		return nil, fmt.Errorf("kfjt: parse article body: %w", err)
	}
	article.Title = title
	if date, publishedAt := kfjtDateValues(shell.Find(".hd .info").First().Text()); date != "" {
		article.Date = date
		article.PublishedAt = publishedAt
	}
	article.Type = kfjtArticleType(doc)
	if article.Type == "" {
		return nil, fmt.Errorf("kfjt: article type is missing")
	}
	kfjtAppendArticleMeta(article, shell)
	kfjtNormalizeContentHTML(article, baseURL)
	kfjtAppendAttachments(article, shell, baseURL)
	article.RawHTML = string(raw)
	if strings.TrimSpace(article.Content) == "" && len(article.Images) == 0 && len(article.Attachments) == 0 {
		return nil, fmt.Errorf("kfjt: article has no body or resources")
	}
	return article, nil
}

func kfjtAppendArticleMeta(article *model.Article, shell *goquery.Selection) {
	if article == nil || shell == nil || shell.Length() == 0 {
		return
	}
	shell.Find(".hd .info span").Each(func(_ int, span *goquery.Selection) {
		text := strings.Join(strings.Fields(span.Text()), " ")
		switch {
		case strings.HasPrefix(text, "来源："):
			article.Source = strings.TrimSpace(strings.TrimPrefix(text, "来源："))
		case strings.HasPrefix(text, "来源:"):
			article.Source = strings.TrimSpace(strings.TrimPrefix(text, "来源:"))
		case strings.HasPrefix(text, "作者："):
			article.Author = strings.TrimSpace(strings.TrimPrefix(text, "作者："))
		case strings.HasPrefix(text, "作者:"):
			article.Author = strings.TrimSpace(strings.TrimPrefix(text, "作者:"))
		}
	})
}

func kfjtAppendAttachments(article *model.Article, shell *goquery.Selection, baseURL string) {
	if article == nil || shell == nil || shell.Length() == 0 {
		return
	}
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		seen[attachment.URL] = true
	}
	shell.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		href := strings.TrimSpace(anchor.AttrOr("href", ""))
		if href == "" || strings.HasPrefix(strings.ToLower(href), "mailto:") || strings.HasPrefix(href, "#") {
			return
		}
		lower := strings.ToLower(href)
		isDownload := strings.Contains(lower, "download.jsp")
		isFile := kfjtAttachmentRE.MatchString(lower)
		if !isDownload && !isFile {
			return
		}
		resolved := kfjtResourceURL(baseURL, href)
		if resolved == "" || seen[resolved] {
			return
		}
		name := strings.TrimSpace(anchor.AttrOr("download", ""))
		if name == "" {
			name = strings.Join(strings.Fields(anchor.Text()), " ")
		}
		name = strings.Trim(strings.TrimSpace(name), "【】[]")
		if name == "" {
			name = resolved
		}
		seen[resolved] = true
		article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: resolved})
	})
}

func kfjtNormalizeContentHTML(article *model.Article, baseURL string) {
	if article == nil || strings.TrimSpace(article.ContentHTML) == "" {
		return
	}
	doc, err := goquery.NewDocumentFromReader(strings.NewReader("<div id=\"kfjt-content-root\">" + article.ContentHTML + "</div>"))
	if err != nil {
		return
	}
	root := doc.Find("#kfjt-content-root").First()
	seenImages := make(map[string]bool, len(article.Images))
	for _, image := range article.Images {
		seenImages[image] = true
	}
	root.Find("img[src]").Each(func(_ int, image *goquery.Selection) {
		resolved := kfjtResourceURL(baseURL, image.AttrOr("src", ""))
		if resolved == "" {
			return
		}
		image.SetAttr("src", resolved)
		if !seenImages[resolved] {
			seenImages[resolved] = true
			article.Images = append(article.Images, resolved)
		}
	})
	root.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		if resolved := kfjtResourceURL(baseURL, anchor.AttrOr("href", "")); resolved != "" {
			anchor.SetAttr("href", resolved)
		}
	})
	if html, err := root.Html(); err == nil {
		article.ContentHTML = html
	}
}

func kfjtArticleType(doc *goquery.Document) string {
	if doc == nil {
		return ""
	}
	items := doc.Find(".breadcrumbs ul li")
	for index := items.Length() - 1; index >= 0; index-- {
		text := strings.Join(strings.Fields(items.Eq(index).Text()), " ")
		if text != "" && text != "首页" && text != "正文" {
			return text
		}
	}
	return ""
}

func kfjtListType(doc *goquery.Document) string {
	if value := strings.TrimSpace(doc.Find(`meta[name="pageTitle"]`).First().AttrOr("content", "")); value != "" {
		return value
	}
	return kfjtArticleType(doc)
}

func kfjtPageType(doc *goquery.Document) string {
	return strings.TrimSpace(doc.Find(`meta[name="pageType"]`).First().AttrOr("content", ""))
}

func kfjtIsHomepage(doc *goquery.Document) bool {
	return kfjtPageType(doc) == "1" && doc.Find(".news-wrap .news-box").Length() > 0
}

func kfjtRejectPage(doc *goquery.Document, kind string) error {
	if doc == nil {
		return fmt.Errorf("kfjt: nil %s response", kind)
	}
	clone := doc.Clone()
	clone.Find("script, style, noscript").Remove()
	text := strings.ToLower(strings.Join(strings.Fields(clone.Text()), " "))
	title := strings.ToLower(strings.TrimSpace(doc.Find("title").First().Text()))
	for _, marker := range []string{"access denied", "cloudflare", "just a moment", "请输入验证码下载附件", "仅限西南交通大学校园网", "系统维护", "404 not found"} {
		if strings.Contains(text, marker) || strings.Contains(title, marker) {
			return fmt.Errorf("kfjt: %s response is an error/captcha page", kind)
		}
	}
	if kfjtPageType(doc) == "" {
		return fmt.Errorf("kfjt: %s response has no page type", kind)
	}
	return nil
}

func kfjtPaginationTotal(doc *goquery.Document) int {
	maxPage := 1
	doc.Find(".pb_sys_common .p_pages .p_no, .pb_sys_common .p_pages .p_no_d").Each(func(_ int, sel *goquery.Selection) {
		if page, err := strconv.Atoi(strings.TrimSpace(sel.Text())); err == nil && page > maxPage {
			maxPage = page
		}
	})
	return maxPage
}

func kfjtDateValues(value string) (date, publishedAt string) {
	value = strings.Join(strings.Fields(strings.ReplaceAll(strings.TrimSpace(value), "\u00a0", " ")), " ")
	if value == "" {
		return "", ""
	}
	if match := kfjtDateTimeRE.FindStringSubmatch(value); match != nil {
		date = kfjtNormalizeDateParts(match[1], match[2], match[3])
		if date == "" {
			return "", ""
		}
		second := match[6]
		if second == "" {
			second = "00"
		}
		hour := match[4]
		if len(hour) == 1 {
			hour = "0" + hour
		}
		return date, fmt.Sprintf("%s %s:%s:%s", date, hour, match[5], second)
	}
	if match := kfjtDateRE.FindStringSubmatch(value); match != nil {
		return kfjtNormalizeDateParts(match[1], match[2], match[3]), ""
	}
	return "", ""
}

func kfjtNormalizeDateParts(year, month, day string) string {
	y, errY := strconv.Atoi(year)
	m, errM := strconv.Atoi(month)
	d, errD := strconv.Atoi(day)
	if errY != nil || errM != nil || errD != nil {
		return ""
	}
	if len(year) == 2 {
		y += 2000
	}
	if y < 2000 || m < 1 || m > 12 || d < 1 || d > 31 {
		return ""
	}
	return fmt.Sprintf("%04d-%02d-%02d", y, m, d)
}

func kfjtArticleURL(baseURL, href string) (string, bool) {
	resolved := kfjtResourceURL(baseURL, href)
	if resolved == "" {
		return "", false
	}
	u, err := url.Parse(resolved)
	if err != nil || !kfjtArticlePathRE.MatchString(u.Path) || !strings.EqualFold(u.Host, "kfjt.swjtu.edu.cn") {
		return "", false
	}
	u.RawQuery = ""
	u.Fragment = ""
	return u.String(), true
}

func kfjtResourceURL(baseURL, href string) string {
	href = strings.TrimSpace(href)
	if href == "" || strings.HasPrefix(strings.ToLower(href), "javascript:") || strings.HasPrefix(href, "#") {
		return ""
	}
	base, err := url.Parse(kfjtCanonicalBase(baseURL))
	if err != nil {
		return ""
	}
	ref, err := url.Parse(href)
	if err != nil {
		return ""
	}
	resolved := base.ResolveReference(ref)
	if resolved.Host == "" {
		return ""
	}
	if strings.EqualFold(resolved.Host, "kfjt.swjtu.edu.cn") {
		resolved.Scheme = "https"
		resolved.Host = "kfjt.swjtu.edu.cn"
	}
	return resolved.String()
}

func kfjtCanonicalBase(baseURL string) string {
	parsed, err := url.Parse(strings.TrimRight(strings.TrimSpace(baseURL), "/"))
	if err != nil || parsed.Host == "" || !strings.EqualFold(parsed.Host, "kfjt.swjtu.edu.cn") {
		return kfjtCanonicalBaseURL
	}
	parsed.Scheme = "https"
	parsed.Host = "kfjt.swjtu.edu.cn"
	parsed.Path = strings.TrimRight(parsed.Path, "/")
	parsed.RawQuery = ""
	parsed.Fragment = ""
	return strings.TrimRight(parsed.String(), "/")
}
