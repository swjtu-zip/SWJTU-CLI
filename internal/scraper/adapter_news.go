// newsSubPages are the normal article feeds exposed by the current news-site
// navigation. jdyw.htm is a legacy list; the current 交大要闻 feed is
// jdyw2.htm. The topic and newspaper pages are intentionally not included:
// they are landing pages rather than homogeneous article lists.
var newsSubPages = []string{
	"jdyw2",
	"zhxw",
	"mtjd",
	"ybdt",
	"index/kxts",
	"index/tzgg",
	"index/xshd",
}

var newsCanonicalSlugs = map[string]string{
	"jdyw":       "jdyw2",
	"jdyw2":      "jdyw2",
	"zhxw":       "zhxw",
	"mtjd":       "mtjd",
	"ybdt":       "ybdt",
	"kxts":       "index/kxts",
	"index/kxts": "index/kxts",
	"tzgg":       "index/tzgg",
	"index/tzgg": "index/tzgg",
	"xshd":       "index/xshd",
	"index/xshd": "index/xshd",
}

var newsDateRe = regexp.MustCompile(`(20\d{2})\s*(?:年|[-/.])\s*(\d{1,2})\s*(?:月|[-/.])\s*(\d{1,2})\s*(?:日|号)?(?:\s*[Tt]?\s*(\d{1,2}):(\d{2})(?::(\d{2}))?)?`)

// Go's regexp engine does not support look-ahead. Find each credit label and
// use the next label's offset as the end of its value; this preserves multiple
// authors such as “作者：王婉 韩旭红”.
var newsCreditLabelRe = regexp.MustCompile(`(?:^|\s)(作者|摄影|编辑|责编|信息员)\s*[:：]\s*`)

// newsAdapter keeps the current news-site templates behind a site-specific
// hook. In particular, it does not fall back to the generic info-link scan:
// the page has a separate “最新新闻” sidebar whose entries must not become
// duplicate feed items.
func init() {
	registerAdapter("news", SiteAdapter{
		SubPages:     newsSubPages,
		ParseList:    parseAdapter_newsList,
		ParseArticle: parseAdapter_newsArticle,
		PageURL:      newsPageURL,
	})
}

// newsPageURL maps the logical page number (1 = newest) to the reverse-numbered
// static files generated by the news site's CMS. For example, with 113 pages,
// logical page 2 is jdyw2/112.htm and logical page 113 is jdyw2/1.htm.
func newsPageURL(baseURL, slug string, page, totalPages int, extension string) string {
	baseURL = strings.TrimRight(baseURL, "/")
	slug = strings.Trim(slug, "/")
	if canonical, ok := newsCanonicalSlugs[slug]; ok {
		slug = canonical
	}
	if extension == "" {
		extension = ".htm"
	} else if !strings.HasPrefix(extension, ".") {
		extension = "." + extension
	}
	if page < 1 || (page > 1 && totalPages < 1) || (totalPages > 0 && page > totalPages) {
		return ""
	}
	if page == 1 {
		return fmt.Sprintf("%s/%s%s", baseURL, slug, extension)
	}

	filePage := totalPages + 1 - page
	return fmt.Sprintf("%s/%s/%d%s", baseURL, slug, filePage, extension)
}

func parseAdapter_newsList(raw []byte, baseURL string) ([]model.NewsItem, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("news list: parse html: %w", err)
	}

	var (
		items    []model.NewsItem
		seen     = make(map[string]bool)
		listRoot *goquery.Selection
		kind     string
		listType string
	)

	// The three main feeds and the ordinary science/notice pages use this
	// exact list. Scoping to .ny-right .list2 excludes the adjacent .ny-news
	// “最新新闻” sidebar and all header/footer links.
	if sel := doc.Find(".ny-right .list2").First(); sel.Length() > 0 {
		listRoot = sel
		kind = "list2"
	} else if sel := doc.Find(".ny-right .list_jh").First(); sel.Length() > 0 {
		// 学术活动 uses cards rather than the list2 template.
		listRoot = sel
		kind = "academic"
	} else if sel := doc.Find(".ny-right .list_zx").First(); sel.Length() > 0 {
		// Keep compatibility with the old jdyw fixture/template, but still
		// require the named content container instead of scanning all links.
		listRoot = sel
		kind = "legacy"
	}
	if listRoot == nil {
		return nil, fmt.Errorf("news list: no recognized article list")
	}
	if container := listRoot.Closest(".ny-right"); container.Length() > 0 {
		listType = strings.TrimSpace(container.Find(".gg-tit").First().Text())
	}
	if listType == "" {
		listType = strings.TrimSpace(listRoot.Parent().Find(".gg-tit").First().Text())
	}
	if listType == "" && kind == "academic" {
		listType = "学术活动"
	}

	ul := listRoot.ChildrenFiltered("ul").First()
	if ul.Length() == 0 {
		return nil, fmt.Errorf("news list: recognized container has no article list")
	}
	rowCount := ul.ChildrenFiltered("li").Length()
	ul.ChildrenFiltered("li").Each(func(_ int, row *goquery.Selection) {
		appendNewsListItem(&items, seen, row, baseURL, kind == "academic", listType)
	})
	if len(items) == 0 {
		if rowCount == 0 {
			// The CMS keeps the normal list shell for a genuinely empty column.
			// Return an empty success only when that shell contains no rows;
			// malformed rows still fail loudly below.
			return []model.NewsItem{}, nil
		}
		return nil, fmt.Errorf("news list: recognized container has no valid article rows")
	}
	return items, nil
}

func appendNewsListItem(items *[]model.NewsItem, seen map[string]bool, row *goquery.Selection, baseURL string, academic bool, listType string) {
	a := row.Find("a[href]").First()
	if a.Length() == 0 {
		return
	}
	href := strings.TrimSpace(a.AttrOr("href", ""))
	if href == "" {
		return
	}

	title := strings.TrimSpace(a.AttrOr("title", ""))
	if title == "" {
		if academic {
			title = strings.TrimSpace(row.Find(".tit").First().Text())
		} else {
			title = strings.TrimSpace(row.Find("h3.bt, h3, h4, .line1, .xw-ul-tt, .news-title").First().Text())
		}
	}
	if title == "" {
		title = strings.TrimSpace(a.Text())
	}
	title = cleanTitle(title)
	if title == "" || !isNewsArticleTitle(title) || len(title) > 200 {
		return
	}

	fullURL := cleanURL(resolveURL(baseURL, href))
	if seen[fullURL] || !isValidNewsURL(fullURL) || isExternalURL(fullURL, baseURL) || !isNewsArticleURL(fullURL) {
		return
	}
	seen[fullURL] = true

	date, publishedAt := "", ""
	if !academic {
		date, publishedAt = newsListDate(row)
	}
	*items = append(*items, model.NewsItem{
		Title:       title,
		URL:         fullURL,
		Date:        date,
		PublishedAt: publishedAt,
		Type:        listType,
		ParsedAt:    time.Now(),
	})
}

func isNewsArticleTitle(title string) bool {
	if isValidNewsTitle(title) {
		return true
	}
	// The shared filter treats every title ending in “》” as a section
	// heading. Academic news legitimately uses a complete book/report title
	// in that form, so retry only after removing the closing quote. Navigation
	// headings such as “通知公告》” remain rejected by the shared filter.
	if !strings.HasSuffix(title, "》") {
		return false
	}
	trimmed := strings.TrimSpace(strings.TrimSuffix(title, "》"))
	return trimmed != "" && isValidNewsTitle(trimmed)
}

func isNewsArticleURL(href string) bool {
	path := strings.ToLower(href)
	if query := strings.IndexAny(path, "?#"); query >= 0 {
		path = path[:query]
	}
	return strings.Contains(path, "/info/") && (strings.HasSuffix(path, ".htm") || strings.HasSuffix(path, ".html"))
}

func newsListDate(row *goquery.Selection) (string, string) {
	dateBlock := row.Find(".date").First()
	if dateBlock.Length() > 0 {
		year := strings.TrimSpace(dateBlock.Find("b").First().Text())
		monthDay := strings.TrimSpace(dateBlock.Find("span").First().Text())
		if year != "" && monthDay != "" {
			if date, publishedAt := normalizeNewsDate(year + "-" + monthDay); date != "" {
				return date, publishedAt
			}
		}
	}

	for _, selector := range []string{".time", "time", ".date-label", ".xw-ul-date", "em"} {
		value := strings.TrimSpace(row.Find(selector).First().Text())
		if value == "" {
			continue
		}
		if date, publishedAt := normalizeNewsDate(value); date != "" {
			return date, publishedAt
		}
		// A legacy list may expose only a preformatted value such as 08-29.
		return strings.Join(strings.Fields(value), " "), ""
	}
	return "", ""
}

// normalizeNewsDate returns a calendar date and, when present, a precise
// timestamp. The live news pages currently publish date-only metadata; the
// clock handling is retained because it prevents future source precision from
// being silently discarded.
func normalizeNewsDate(raw string) (string, string) {
	raw = strings.Join(strings.Fields(strings.TrimSpace(raw)), " ")
	match := newsDateRe.FindStringSubmatch(raw)
	if match == nil {
		return "", ""
	}
	date := normalizeDateParts(match[1], match[2], match[3])
	if date == "" {
		return "", ""
	}
	if match[4] == "" {
		return date, date
	}
	second := match[6]
	if second == "" {
		second = "00"
	}
	return date, fmt.Sprintf("%s %02s:%s:%s", date, match[4], match[5], second)
}

func parseAdapter_newsArticle(raw []byte, baseURL string) (*model.Article, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("news article: parse html: %w", err)
	}

	// Requiring the article shell is deliberate. A news homepage contains
	// headings and info links, but no .art-main/.v_news_content article body.
	root := doc.Find(".art-main").First()
	if root.Length() == 0 {
		return nil, fmt.Errorf("news article: no article shell")
	}

	titleSel := root.Find(".art-tit h1, .art-tit h2, .art-tit h3").First()
	title := strings.TrimSpace(titleSel.Text())
	if title == "" {
		title = strings.TrimSpace(doc.Find(`meta[name="pageTitle"]`).AttrOr("content", ""))
	}
	if title == "" {
		return nil, fmt.Errorf("news article: no title")
	}

	contentSel := root.Find(".art-body .v_news_content").First()
	if contentSel.Length() == 0 {
		contentSel = root.Find(".v_news_content").First()
	}
	if contentSel.Length() == 0 {
		return nil, fmt.Errorf("news article: no article body")
	}

	article := &model.Article{
		Title: title,
	}
	root.Find(".art-tit p span, .art-tit .news-source span, .news_source span").Each(func(_ int, sel *goquery.Selection) {
		label, value := newsLabeledValue(sel.Text())
		switch label {
		case "source":
			if article.Source == "" {
				article.Source = value
			}
		case "date":
			if article.Date == "" {
				article.Date, article.PublishedAt = normalizeNewsDate(value)
			}
		case "type":
			if article.Type == "" {
				article.Type = value
			}
		}
	})

	if article.Type == "" {
		article.Type = newsArticleType(doc)
	}
	// Generic labels are a fallback for old variants of the same CMS. They run
	// after the exact current-template selectors and breadcrumb type, so a
	// source containing full-width punctuation or parentheses is kept verbatim
	// and a body field such as “类型：比赛” cannot replace the real column.
	fillGenericMeta(doc, article, titleSel, contentSel)
	parseNewsCredits(root, article)

	var contentParts []string
	contentSel.Find("p, h1, h2, h3, h4, h5, h6, li, blockquote, pre, td, th").Each(func(_ int, sel *goquery.Selection) {
		if sel.ParentsFiltered("p, h1, h2, h3, h4, h5, h6, li, blockquote, pre, td, th").Length() > 0 {
			return
		}
		if text := strings.Join(strings.Fields(sel.Text()), " "); text != "" {
			contentParts = append(contentParts, text)
		}
	})
	if len(contentParts) == 0 {
		if text := strings.Join(strings.Fields(contentSel.Text()), " "); text != "" {
			contentParts = append(contentParts, text)
		}
	}
	article.Content = strings.Join(contentParts, "\n\n")

	seenImages := make(map[string]bool)
	contentSel.Find("img").Each(func(_ int, sel *goquery.Selection) {
		var resolved string
		for _, attr := range []string{"src", "data-src", "data-original", "data-lazy-src", "orisrc"} {
			src := strings.TrimSpace(sel.AttrOr(attr, ""))
			if src == "" {
				continue
			}
			if resolved = bodaResourceURL(baseURL, src); resolved != "" {
				break
			}
		}
		if resolved == "" {
			for _, attr := range []string{"src", "data-src", "data-original", "data-lazy-src", "orisrc"} {
				sel.RemoveAttr(attr)
			}
			return
		}
		if !seenImages[resolved] {
			seenImages[resolved] = true
			article.Images = append(article.Images, resolved)
		}
		sel.SetAttr("src", resolved)
	})

	collectNewsAttachments(root, contentSel, baseURL, article)
	if html, htmlErr := contentSel.Html(); htmlErr == nil {
		article.ContentHTML = html
	}
	return article, nil
}

func newsLabeledValue(raw string) (string, string) {
	value := strings.Join(strings.Fields(strings.TrimSpace(raw)), " ")
	for _, entry := range []struct {
		label string
		kind  string
	}{
		{label: "信息来源", kind: "source"},
		{label: "来源", kind: "source"},
		{label: "日期", kind: "date"},
		{label: "发布时间", kind: "date"},
		{label: "发布日期", kind: "date"},
		{label: "文章类型", kind: "type"},
		{label: "信息类型", kind: "type"},
		{label: "类型", kind: "type"},
		{label: "分类", kind: "type"},
		{label: "类别", kind: "type"},
		{label: "栏目", kind: "type"},
	} {
		for _, separator := range []string{"：", ":"} {
			prefix := entry.label + separator
			if strings.HasPrefix(value, prefix) {
				return entry.kind, strings.TrimSpace(strings.TrimPrefix(value, prefix))
			}
		}
	}
	return "", ""
}

func parseNewsCredits(root *goquery.Selection, article *model.Article) {
	credits := root.Find(".xxx").First()
	if credits.Length() == 0 {
		return
	}
	text := strings.Join(strings.Fields(credits.Text()), " ")
	infoReporter := ""
	matches := newsCreditLabelRe.FindAllStringSubmatchIndex(text, -1)
	for i, match := range matches {
		valueEnd := len(text)
		if i+1 < len(matches) {
			valueEnd = matches[i+1][0]
		}
		value := strings.TrimSpace(text[match[1]:valueEnd])
		if value == "" {
			continue
		}
		switch text[match[2]:match[3]] {
		case "作者":
			article.Author = value
		case "摄影":
			article.Photographer = value
		case "编辑", "责编":
			article.Editor = value
		case "信息员":
			infoReporter = value
		}
	}
	if article.Author == "" {
		article.Author = infoReporter
	}
}

var newsAttachmentExtensions = []string{
	".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx", ".pdf",
	".zip", ".rar", ".7z", ".txt", ".csv",
}

func collectNewsAttachments(root, contentSel *goquery.Selection, baseURL string, article *model.Article) {
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		seen[attachment.URL] = true
	}

	root.Find("a[href]").Each(func(_ int, sel *goquery.Selection) {
		href := strings.TrimSpace(sel.AttrOr("href", ""))
		if href == "" || !isNewsAttachmentLink(sel, href) {
			return
		}
		resolved := bodaResourceURL(baseURL, href)
		if resolved == "" || newsIsCaptchaDownloadURL(resolved) {
			return
		}
		if seen[resolved] {
			return
		}

		name := strings.TrimSpace(sel.AttrOr("download", ""))
		if name == "" {
			name = strings.TrimSpace(sel.AttrOr("name", ""))
		}
		if name == "" {
			name = strings.Join(strings.Fields(sel.Text()), " ")
		}
		if name == "" {
			name = href
		}
		seen[resolved] = true
		article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: resolved})
		if sel.ParentsFiltered(".v_news_content").Length() > 0 {
			sel.SetAttr("href", resolved)
		}
	})
}

func newsArticleType(doc *goquery.Document) string {
	var articleType string
	doc.Find(".position .weizhi a").Each(func(_ int, sel *goquery.Selection) {
		value := strings.TrimSpace(sel.Text())
		if value == "" || value == "首页" {
			return
		}
		articleType = value
	})
	return articleType
}

func newsIsCaptchaDownloadURL(raw string) bool {
	parsed, err := url.Parse(raw)
	return err == nil && strings.EqualFold(parsed.Path, "/system/_content/download.jsp")
}

func isNewsAttachmentLink(sel *goquery.Selection, href string) bool {
	if sel.Find("img").Length() > 0 && sel.AttrOr("download", "") == "" && sel.AttrOr("name", "") == "" {
		return false
	}
	if sel.AttrOr("download", "") != "" {
		return true
	}
	if newsHasAttachmentExtension(sel.AttrOr("name", "")) {
		return true
	}
	if newsHasAttachmentExtension(href) {
		return true
	}
	for _, ancestor := range []string{"li", ".attachment", ".attachments", ".news-attachment"} {
		parent := sel.Closest(ancestor)
		if parent.Length() > 0 && strings.Contains(parent.Text(), "附件") {
			return true
		}
	}
	return false
}

func newsHasAttachmentExtension(value string) bool {
	value = strings.ToLower(value)
	for _, ext := range newsAttachmentExtensions {
		if strings.Contains(value, ext) {
			return true
		}
	}
	return false
}
