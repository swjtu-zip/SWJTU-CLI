// oalmPageURL maps logical pages (1 = newest) to the reverse-numbered static
// files generated by Visual SiteBuilder: slug.htm, slug/{N-1}.htm, ..., 1.htm.
func oalmPageURL(baseURL, slug string, page, totalPages int, extension string) string {
	baseURL = oalmCanonicalBase(baseURL)
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	if slug == "" || strings.EqualFold(slug, "index") {
		slug = "index"
	}
	if extension == "" {
		extension = ".htm"
	} else if !strings.HasPrefix(extension, ".") {
		extension = "." + extension
	}
	if page < 1 {
		page = 1
	}
	if page <= 1 || totalPages <= 1 {
		return fmt.Sprintf("%s/%s%s", baseURL, slug, extension)
	}
	physical := totalPages - page + 1
	if physical < 1 {
		physical = 1
	}
	return fmt.Sprintf("%s/%s/%d%s", baseURL, slug, physical, extension)
}

func oalmCanonicalBase(baseURL string) string {
	baseURL = strings.TrimRight(strings.TrimSpace(baseURL), "/")
	if baseURL == "" {
		return oalmCanonicalBaseURL
	}
	return oalmCanonicalBaseURL
}

func oalmKnownFeed(slug string) bool {
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	if strings.EqualFold(slug, "index") || slug == "" {
		return true
	}
	_, ok := oalmRouteTypes[slug]
	return ok
}

// oalmListPage owns the first-page lookup so page N can be translated to the
// source's reverse-numbered filename and out-of-range requests cannot silently
// return page 1 again.
func oalmListPage(slug string, page int) ([]model.NewsItem, int, error) {
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	if slug == "" {
		slug = "index"
	}
	if page < 1 {
		page = 1
	}
	if !oalmKnownFeed(slug) {
		return nil, 0, fmt.Errorf("oalm: %q is not an article-list route", slug)
	}

	firstURL := oalmPageURL(oalmCanonicalBaseURL, slug, 1, 0, ".htm")
	firstBody, err := fetch(firstURL)
	if err != nil {
		return nil, 0, fmt.Errorf("oalm: fetch first page %s: %w", slug, err)
	}
	firstDoc, err := oalmDocument(firstBody)
	if err != nil {
		return nil, 0, err
	}
	if strings.EqualFold(slug, "index") {
		if page != 1 {
			return nil, 1, fmt.Errorf("oalm: homepage has only one page")
		}
		items, parseErr := parseOalmHomepage(firstDoc, oalmCanonicalBaseURL)
		if parseErr != nil {
			return nil, 1, parseErr
		}
		return items, 1, nil
	}

	totalPages, err := oalmPageCount(firstDoc, slug)
	if err != nil {
		return nil, 0, err
	}
	if page > totalPages {
		return nil, totalPages, fmt.Errorf("oalm: requested page %d beyond %d for %s", page, totalPages, slug)
	}

	body := firstBody
	if page != 1 {
		body, err = fetch(oalmPageURL(oalmCanonicalBaseURL, slug, page, totalPages, ".htm"))
		if err != nil {
			return nil, totalPages, fmt.Errorf("oalm: fetch page %d/%d for %s: %w", page, totalPages, slug, err)
		}
	}
	items, err := parseAdapter_oalmList(body, oalmCanonicalBaseURL)
	return items, totalPages, err
}

func oalmTotalPages(slug string) (int, error) {
	slug = strings.Trim(strings.TrimSpace(slug), "/")
	if slug == "" || strings.EqualFold(slug, "index") {
		return 1, nil
	}
	if !oalmKnownFeed(slug) {
		return 0, fmt.Errorf("oalm: %q is not an article-list route", slug)
	}
	body, err := fetch(oalmPageURL(oalmCanonicalBaseURL, slug, 1, 0, ".htm"))
	if err != nil {
		return 0, fmt.Errorf("oalm: fetch first page for %s: %w", slug, err)
	}
	doc, err := oalmDocument(body)
	if err != nil {
		return 0, err
	}
	return oalmPageCount(doc, slug)
}

func oalmDocument(raw []byte) (*goquery.Document, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("oalm: parse HTML: %w", err)
	}
	if strings.Contains(strings.ToLower(doc.Text()), "503错误提示") || strings.Contains(strings.ToLower(doc.Text()), "服务不可用") {
		return nil, fmt.Errorf("oalm: source returned an error page")
	}
	return doc, nil
}

func oalmPageCount(doc *goquery.Document, slug string) (int, error) {
	if strings.TrimSpace(doc.Find(`meta[name="pageType"]`).AttrOr("content", "")) != "2" {
		return 0, fmt.Errorf("oalm: %s is not a list page", slug)
	}
	if oalmListContainer(doc).Length() == 0 {
		return 0, fmt.Errorf("oalm: %s is a static page, not an article list", slug)
	}
	maxPage := 0
	doc.Find(".p_pages .p_no_d, .p_pages .p_no a").Each(func(_ int, sel *goquery.Selection) {
		value := strings.TrimSpace(sel.Text())
		if !oalmPageNumberRE.MatchString(value) {
			return
		}
		page, convErr := strconv.Atoi(value)
		if convErr == nil && page > maxPage {
			maxPage = page
		}
	})
	if maxPage > 0 {
		return maxPage, nil
	}
	if oalmRows(doc).Length() > 0 || oalmExplicitEmpty(doc) {
		return 1, nil
	}
	return 0, fmt.Errorf("oalm: %s has no pagination or article rows", slug)
}

func parseAdapter_oalmList(raw []byte, baseURL string) ([]model.NewsItem, error) {
	doc, err := oalmDocument(raw)
	if err != nil {
		return nil, err
	}
	pageType := strings.TrimSpace(doc.Find(`meta[name="pageType"]`).AttrOr("content", ""))
	if pageType == "1" || oalmIsHomepage(doc) {
		return parseOalmHomepage(doc, baseURL)
	}
	if pageType != "2" {
		return nil, fmt.Errorf("oalm: page is not a list page (pageType %q)", pageType)
	}
	if oalmListContainer(doc).Length() == 0 {
		return nil, fmt.Errorf("oalm: page is a static page, not an article list")
	}
	rows := oalmRows(doc)
	if rows.Length() == 0 {
		if oalmExplicitEmpty(doc) {
			return []model.NewsItem{}, nil
		}
		return nil, fmt.Errorf("oalm: recognized list has no article rows")
	}

	typ := oalmListType(doc)
	if typ == "" {
		return nil, fmt.Errorf("oalm: list type is missing")
	}
	items := make([]model.NewsItem, 0, rows.Length())
	seen := make(map[string]bool, rows.Length())
	rows.Each(func(_ int, row *goquery.Selection) {
		anchor := row.Find("a[href]").First()
		if anchor.Length() == 0 {
			return
		}
		fullURL, ok := oalmArticleURL(baseURL, anchor.AttrOr("href", ""))
		if !ok || seen[fullURL] {
			return
		}
		title := oalmRowTitle(row, anchor)
		if !oalmValidTitle(title) {
			return
		}
		date, publishedAt := oalmRowDate(row)
		seen[fullURL] = true
		items = append(items, model.NewsItem{
			Title:       title,
			URL:         fullURL,
			Date:        date,
			PublishedAt: publishedAt,
			Type:        typ,
			ParsedAt:    time.Now(),
		})
	})
	return items, nil
}

func oalmListContainer(doc *goquery.Document) *goquery.Selection {
	if list := doc.Find(".xwdt-right-content ul.news-list").First(); list.Length() > 0 {
		return list
	}
	return doc.Find(".tzgg-right-content ul.tzgg-news-column").First()
}

func oalmRows(doc *goquery.Document) *goquery.Selection {
	return doc.Find(".xwdt-right-content li[id^='line_u9_'], .tzgg-right-content li[id^='line_u9_']")
}

func oalmExplicitEmpty(doc *goquery.Document) bool {
	scope := oalmListContainer(doc)
	if scope.Length() == 0 {
		return false
	}
	text := strings.Join(strings.Fields(scope.Text()), " ")
	for _, marker := range []string{"暂无数据", "暂无内容", "暂无信息", "没有相关信息", "无相关信息"} {
		if strings.Contains(text, marker) {
			return true
		}
	}
	return false
}

func oalmListType(doc *goquery.Document) string {
	for _, selector := range []string{".xwdt-right-content .current-title", ".tzgg-right-content .current-title", ".top-msg .current-title", ".current-title"} {
		if text := strings.Join(strings.Fields(doc.Find(selector).First().Text()), " "); text != "" {
			return text
		}
	}
	spans := doc.Find(".xwdt-right-content .mbx span, .tzgg-right-content .mbx span")
	for i := spans.Length() - 1; i >= 0; i-- {
		text := strings.Join(strings.Fields(spans.Eq(i).Text()), " ")
		if text != "" && text != "首页" && text != "正文" {
			return text
		}
	}
	return ""
}

func oalmRowTitle(row, anchor *goquery.Selection) string {
	for _, selector := range []string{".right .title", ".bt", ".text", ".content", ".line1"} {
		if found := row.Find(selector).First(); found.Length() > 0 {
			if title := strings.Join(strings.Fields(found.Text()), " "); title != "" {
				return cleanTitle(title)
			}
		}
	}
	if title := strings.TrimSpace(anchor.AttrOr("title", "")); title != "" {
		return cleanTitle(title)
	}
	clone := anchor.Clone()
	clone.Find(".time, .date, .time-box, .time-author-eyes, .author, .eyes, img").Remove()
	return cleanTitle(strings.Join(strings.Fields(clone.Text()), " "))
}

func oalmRowDate(row *goquery.Selection) (string, string) {
	for _, selector := range []string{".time-author-eyes", ".time-box"} {
		if found := row.Find(selector).First(); found.Length() > 0 {
			if date, publishedAt := oalmDateValues(found.Text()); date != "" {
				return date, publishedAt
			}
		}
	}
	yearMonth := strings.TrimSpace(row.Find(".time-box .date").First().Text())
	day := strings.TrimSpace(row.Find(".time-box .hao").First().Text())
	if yearMonth != "" && day != "" {
		if date, publishedAt := oalmDateValues(yearMonth + "-" + day); date != "" {
			return date, publishedAt
		}
	}
	return oalmDateValues(row.Text())
}

func oalmDateValues(raw string) (string, string) {
	raw = strings.Join(strings.Fields(strings.ReplaceAll(raw, "\u00a0", " ")), " ")
	if raw == "" {
		return "", ""
	}
	if match := oalmDateTimeRE.FindString(raw); match != "" {
		publishedAt := normalizePublishedAt(match)
		if len(publishedAt) >= 10 {
			return publishedAt[:10], publishedAt
		}
	}
	if match := oalmDateRE.FindString(raw); match != "" {
		date := normalizePublishedAt(match)
		if len(date) >= 10 {
			// The source exposes only a calendar date on list/detail pages.
			// Do not manufacture a time-of-day; the BodaSite wrapper may add
			// its legacy midnight normalization after parsing.
			return date[:10], ""
		}
	}
	return "", ""
}

func parseOalmHomepage(doc *goquery.Document, baseURL string) ([]model.NewsItem, error) {
	if !oalmIsHomepage(doc) {
		return nil, fmt.Errorf("oalm: page is not the homepage")
	}
	items := make([]model.NewsItem, 0)
	seen := make(map[string]int)

	add := func(row *goquery.Selection, typ string) {
		if row == nil || row.Length() == 0 {
			return
		}
		anchor := row.Find("a[href]").First()
		if anchor.Length() == 0 && row.Is("a[href]") {
			anchor = row
		}
		if anchor.Length() == 0 {
			return
		}
		title := ""
		for _, selector := range []string{".text-desc .line1", ".content", ".line1", ".text"} {
			if found := row.Find(selector).First(); found.Length() > 0 {
				title = strings.Join(strings.Fields(found.Text()), " ")
				if title != "" {
					break
				}
			}
		}
		if title == "" {
			title = strings.TrimSpace(anchor.AttrOr("title", ""))
		}
		if title == "" {
			clone := anchor.Clone()
			clone.Find(".time, .date, time, img").Remove()
			title = strings.Join(strings.Fields(clone.Text()), " ")
		}
		dateText := row.Find(".time-box, .time, time").First().Text()
		if dateText == "" {
			dateText = row.Text()
		}
		date, publishedAt := oalmDateValues(dateText)
		if typ == "" {
			typ = oalmTypeFromURL(anchor.AttrOr("href", ""))
		}
		if typ == "" {
			typ = "首页模块"
		}
		oalmAppendItem(&items, seen, anchor.AttrOr("href", ""), title, date, publishedAt, typ, baseURL)
	}

	// The carousel contains four placeholder/service links and, occasionally,
	// a real local article. Only /info/... links are accepted.
	doc.Find(".main-banner .swiper-slide").Each(func(_ int, slide *goquery.Selection) {
		add(slide, "首页轮播")
	})

	// This top strip and both tab panels are present in the HTML even when the
	// second tab is hidden by JavaScript.
	doc.Find("main.index-main .boxa > li, .index-main .boxa > li").Each(func(_ int, row *goquery.Selection) {
		add(row, "")
	})
	doc.Find("main.index-main .inform, .index-main .inform").Each(func(_ int, box *goquery.Selection) {
		tabs := box.Find(".tabNav li")
		box.Find(".tabCon .tabcons").Each(func(index int, panel *goquery.Selection) {
			typ := ""
			if index < tabs.Length() {
				typ = strings.Join(strings.Fields(tabs.Eq(index).Text()), " ")
			}
			panel.Find("li").Each(func(_ int, row *goquery.Selection) { add(row, typ) })
		})
	})

	// Three article cards are below the fold and are not part of the visible
	// tab. They are intentionally parsed independently of the tab panels.
	doc.Find(".part-3 .every-card").Each(func(_ int, card *goquery.Selection) {
		typ := strings.Join(strings.Fields(card.Find(".big-title .left").First().Text()), " ")
		card.Find("ul > li").Each(func(_ int, row *goquery.Selection) { add(row, typ) })
	})

	if len(items) == 0 {
		return nil, fmt.Errorf("oalm: homepage contains no local article entries")
	}
	return items, nil
}

func oalmIsHomepage(doc *goquery.Document) bool {
	pageType := strings.TrimSpace(doc.Find(`meta[name="pageType"]`).AttrOr("content", ""))
	return pageType == "1" || doc.Find("main.index-main, .main-banner").Length() > 0
}

func oalmAppendItem(items *[]model.NewsItem, seen map[string]int, href, title, date, publishedAt, typ, baseURL string) {
	fullURL, ok := oalmArticleURL(baseURL, href)
	if !ok {
		return
	}
	title = cleanTitle(strings.TrimSpace(title))
	if !oalmValidTitle(title) {
		return
	}
	typ = strings.TrimSpace(typ)
	if index, exists := seen[fullURL]; exists {
		current := &(*items)[index]
		if current.Date == "" && date != "" {
			current.Date = date
			current.PublishedAt = publishedAt
		}
		if (strings.Contains(current.Title, "...") || strings.Contains(current.Title, "…")) && len([]rune(title)) > len([]rune(current.Title)) {
			current.Title = title
		}
		if (current.Type == "" || current.Type == "首页模块" || current.Type == "首页轮播") && typ != "" {
			current.Type = typ
		}
		return
	}
	seen[fullURL] = len(*items)
	*items = append(*items, model.NewsItem{
		Title:       title,
		URL:         fullURL,
		Date:        date,
		PublishedAt: publishedAt,
		Type:        typ,
		ParsedAt:    time.Now(),
	})
}

func oalmArticleURL(baseURL, href string) (string, bool) {
	href = strings.TrimSpace(href)
	if href == "" || strings.HasPrefix(href, "#") || strings.HasPrefix(strings.ToLower(href), "javascript:") {
		return "", false
	}
	full := resolveURL(oalmCanonicalBase(baseURL), href)
	parsed, err := url.Parse(full)
	if err != nil || parsed.Hostname() == "" || !oalmArticlePathRE.MatchString(parsed.Path) {
		return "", false
	}
	base, _ := url.Parse(oalmCanonicalBaseURL)
	if !strings.EqualFold(parsed.Hostname(), base.Hostname()) {
		return "", false
	}
	parsed.Scheme = base.Scheme
	parsed.Host = base.Host
	return parsed.String(), true
}

func oalmTypeFromURL(href string) string {
	parsed, err := url.Parse(href)
	if err != nil {
		return ""
	}
	parts := strings.Split(strings.Trim(parsed.Path, "/"), "/")
	if len(parts) >= 3 {
		return oalmChannelTypes[parts[1]]
	}
	return ""
}

func oalmValidTitle(title string) bool {
	title = strings.Join(strings.Fields(strings.TrimSpace(title)), " ")
	if title == "" || len([]rune(title)) < 2 || len([]rune(title)) > 300 {
		return false
	}
	switch title {
	case "首页", "更多", "新闻动态", "通知公告", "党建工会", "设备家具科", "房屋资源科", "实验室安全科", "国家法律法规", "校内管理文件", "调剂信息", "信息公示", "安全信息":
		return false
	}
	return true
}

func parseAdapter_oalmArticle(raw []byte, baseURL string) (*model.Article, error) {
	doc, err := oalmDocument(raw)
	if err != nil {
		return nil, err
	}
	pageType := strings.TrimSpace(doc.Find(`meta[name="pageType"]`).AttrOr("content", ""))
	if pageType != "3" {
		return nil, fmt.Errorf("oalm: page is not an article (pageType %q)", pageType)
	}
	shell := doc.Find(".news-details-desc .zw, .zw").First()
	if shell.Length() == 0 {
		return nil, fmt.Errorf("oalm: article shell is missing")
	}
	title := strings.Join(strings.Fields(shell.Find(".zw-title").First().Text()), " ")
	if !oalmValidTitle(title) {
		return nil, fmt.Errorf("oalm: article title is missing")
	}
	if shell.Find(".v_news_content").First().Length() == 0 {
		return nil, fmt.Errorf("oalm: article content shell is missing")
	}

	article, err := parseBodaArticle(raw, oalmCanonicalBase(baseURL))
	if err != nil {
		return nil, fmt.Errorf("oalm: parse article body: %w", err)
	}
	article.Title = title
	if date, publishedAt := oalmDateValues(shell.Find(".msg").First().Text()); date != "" {
		article.Date = date
		article.PublishedAt = publishedAt
	}
	article.Type = oalmArticleType(doc)
	if article.Type == "" {
		return nil, fmt.Errorf("oalm: article type is missing")
	}
	oalmAppendAttachments(article, doc, oalmCanonicalBase(baseURL))
	normalizeArticlePublishedAt(article)
	if strings.TrimSpace(article.Content) == "" && len(article.Images) == 0 && len(article.Attachments) == 0 {
		return nil, fmt.Errorf("oalm: article has no body or resources")
	}
	return article, nil
}

func oalmArticleType(doc *goquery.Document) string {
	spans := doc.Find(".news-details-desc .mbx span, .mbx span")
	for i := spans.Length() - 1; i >= 0; i-- {
		text := strings.Join(strings.Fields(spans.Eq(i).Text()), " ")
		if text != "" && text != "首页" && text != "正文" {
			return text
		}
	}
	return ""
}

func oalmAppendAttachments(article *model.Article, doc *goquery.Document, baseURL string) {
	if article == nil {
		return
	}
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		seen[attachment.URL] = true
	}
	doc.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		href := strings.TrimSpace(anchor.AttrOr("href", ""))
		if !strings.Contains(strings.ToLower(href), "download.jsp") {
			return
		}
		li := anchor.Closest("li")
		if li.Length() == 0 || !strings.Contains(strings.Join(strings.Fields(li.Text()), " "), "附件") {
			return
		}
		name := strings.Join(strings.Fields(anchor.Text()), " ")
		if name == "" {
			name = strings.TrimSpace(anchor.AttrOr("download", ""))
		}
		fullURL := resolveURL(baseURL, href)
		if name == "" || fullURL == "" || seen[fullURL] {
			return
		}
		seen[fullURL] = true
		article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: fullURL})
	})
}
