var (
	glxyArticlePathRE = regexp.MustCompile(`(?i)^/info/[0-9]+/[0-9]+\.html?$`)
	glxyClockRE       = regexp.MustCompile(`(?:\d{1,2}\s*[:：]\s*\d{2}|\d{1,2}\s*时\s*\d{2}\s*分)`)
	glxyAttachmentRE  = regexp.MustCompile(`(?i)\.(?:docx?|xlsx?|pptx?|pdf|zip|rar|7z|txt|csv|wps|rtf)(?:$|[?#])`)
)

func init() {
	// sites.go retains the legacy HTTP fallback for this host. The live site
	// redirects/serves canonically over HTTPS, so make this site's own adapter
	// authoritative without changing the shared registry or other adapters.
	if site := AllSites["glxy"]; site != nil {
		site.BaseURL = glxyBaseURL
	}
	registerAdapter("glxy", SiteAdapter{
		SubPages:     glxySubPages,
		ParseList:    parseGlxyNews,
		ParseArticle: parseGlxyArticle,
		PageURL:      glxyPageURL,
		TotalPages:   glxyTotalPages,
	})
}

// glxyPageURL maps logical pages (1 = newest) to the reverse-numbered files
// generated by Visual SiteBuilder: slug.htm, slug/{total-1}.htm, ..., slug/1.htm.
func glxyPageURL(baseURL, slug string, page, totalPages int, extension string) string {
	baseURL = strings.TrimRight(strings.TrimSpace(baseURL), "/")
	slug = strings.Trim(slug, "/")
	if slug == "" {
		slug = "index"
	}
	if extension == "" {
		extension = ".htm"
	}
	if !strings.HasPrefix(extension, ".") {
		extension = "." + extension
	}
	if page < 1 {
		page = 1
	}
	if page <= 1 {
		return baseURL + "/" + slug + extension
	}
	filePage := page
	if totalPages > 1 {
		filePage = totalPages - page + 1
	}
	if filePage < 1 {
		filePage = 1
	}
	return baseURL + "/" + slug + "/" + strconv.Itoa(filePage) + extension
}

func parseGlxyNews(raw []byte, baseURL string) ([]model.NewsItem, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("parse glxy list: %w", err)
	}
	if glxyLooksLikeErrorPage(doc) {
		return nil, fmt.Errorf("glxy list is an error or verification page")
	}

	if glxyIsHomepage(doc) {
		items := parseGlxyHomepage(doc, baseURL)
		if len(items) == 0 {
			return nil, fmt.Errorf("glxy homepage contains no article entries")
		}
		return items, nil
	}

	if list := doc.Find("ul.xw-ul").First(); list.Length() > 0 {
		return parseGlxyListRows(list, baseURL, glxyListType(doc)), nil
	}
	if list := doc.Find("ul.dj_lb1").First(); list.Length() > 0 {
		return parseGlxyListRows(list, baseURL, glxyListType(doc)), nil
	}
	return nil, fmt.Errorf("glxy page is not a supported homepage or article list")
}

func parseGlxyListRows(list *goquery.Selection, baseURL, typ string) []model.NewsItem {
	rows := list.ChildrenFiltered("li")
	items := make([]model.NewsItem, 0, rows.Length())
	seen := make(map[string]bool, rows.Length())
	rows.Each(func(_ int, row *goquery.Selection) {
		anchor := row.Find("a[href]").First()
		if anchor.Length() == 0 {
			return
		}
		fullURL, ok := glxyArticleURL(baseURL, anchor.AttrOr("href", ""))
		if !ok || seen[fullURL] {
			return
		}
		title := glxyListRowTitle(row)
		if title == "" || utf8.RuneCountInString(title) > 200 || !isValidNewsTitle(title) {
			return
		}
		date, publishedAt := glxyListRowDate(row)
		seen[fullURL] = true
		items = append(items, model.NewsItem{
			Title:       title,
			URL:         fullURL,
			Date:        date,
			PublishedAt: publishedAt,
			Type:        typ,
			ParsedAt:    time.Now(),
		})
	})
	return items
}

func glxyListRowTitle(row *goquery.Selection) string {
	for _, selector := range []string{".xw-ul-tt", ".txt-elise", ".dj_lb1-tt", ".title", "h3", "h4"} {
		if found := row.Find(selector).First(); found.Length() > 0 {
			clone := found.Clone()
			clone.Find(".xw-ul-date, .date, .time, time, span.sj, span").Remove()
			if title := cleanTitle(strings.Join(strings.Fields(htmlstd.UnescapeString(clone.Text())), " ")); title != "" {
				return title
			}
		}
	}
	anchor := row.Find("a[href]").First()
	if anchor.Length() == 0 {
		return ""
	}
	clone := anchor.Clone()
	clone.Find(".xw-ul-date, .date, .time, time, span.sj, span").Remove()
	return cleanTitle(strings.Join(strings.Fields(htmlstd.UnescapeString(clone.Text())), " "))
}

func glxyListRowDate(row *goquery.Selection) (string, string) {
	if dateBlock := row.Find(".xw-ul-date").First(); dateBlock.Length() > 0 {
		day := strings.TrimSpace(dateBlock.Find("span").First().Text())
		yearMonth := strings.TrimSpace(dateBlock.Find("font").First().Text())
		if day != "" && yearMonth != "" {
			if date, publishedAt := glxyDateValues(yearMonth + "/" + day); date != "" {
				return date, publishedAt
			}
		}
	}
	for _, selector := range []string{".sj", ".date", ".time", "time", ".one-date"} {
		if value := strings.TrimSpace(row.Find(selector).First().Text()); value != "" {
			return glxyDateValues(value)
		}
	}
	return "", ""
}

func parseGlxyHomepage(doc *goquery.Document, baseURL string) []model.NewsItem {
	items := make([]model.NewsItem, 0)
	seen := make(map[string]int)

	doc.Find(".page-one .one-list > li").Each(func(_ int, row *goquery.Selection) {
		addGlxyHomepageItem(&items, seen, row, baseURL, "学院新闻", ".one-list-tt", ".one-date")
	})

	// The source intentionally spells this container page-tow. Keep the
	// typo-specific selector and a page-two fallback for a future correction.
	for _, selector := range []string{".page-tow .tow-right", ".page-two .tow-right"} {
		doc.Find(selector).Each(func(_ int, section *goquery.Selection) {
			typ := strings.Join(strings.Fields(section.Find(".tow-right-title span").First().Text()), " ")
			if typ == "" {
				typ = strings.Join(strings.Fields(section.Find(".tow-right-title").First().Text()), " ")
			}
			section.Find(".tow-right-ul > li").Each(func(_ int, row *goquery.Selection) {
				addGlxyHomepageItem(&items, seen, row, baseURL, typ, ".txt-elise", "span")
			})
		})
	}

	doc.Find(".page-three .three-ul > li").Each(func(_ int, row *goquery.Selection) {
		addGlxyHomepageItem(&items, seen, row, baseURL, "学术活动", ".three-ul-tt", "")
	})
	doc.Find(".page-four .four-list > li").Each(func(_ int, row *goquery.Selection) {
		addGlxyHomepageItem(&items, seen, row, baseURL, "科研成果", ".four-list-tt", "")
	})
	return items
}

func addGlxyHomepageItem(items *[]model.NewsItem, seen map[string]int, row *goquery.Selection, baseURL, typ, titleSelector, dateSelector string) {
	if row == nil || row.Length() == 0 {
		return
	}
	anchor := row.Find("a[href]").First()
	if anchor.Length() == 0 {
		return
	}
	fullURL, ok := glxyArticleURL(baseURL, anchor.AttrOr("href", ""))
	if !ok {
		return
	}
	title := ""
	if titleSelector != "" {
		found := row.Find(titleSelector).First()
		if found.Length() > 0 {
			clone := found.Clone()
			clone.Find("span, .date, .time, time").Remove()
			title = clone.Text()
		}
	}
	if title == "" {
		clone := anchor.Clone()
		clone.Find(".xw-ul-date, .one-date, .date, .time, time, span").Remove()
		title = clone.Text()
	}
	title = cleanTitle(strings.Join(strings.Fields(htmlstd.UnescapeString(title)), " "))
	if title == "" || utf8.RuneCountInString(title) > 200 || !isValidNewsTitle(title) {
		return
	}
	date, publishedAt := "", ""
	if dateSelector != "" {
		if found := row.Find(dateSelector).First(); found.Length() > 0 {
			date, publishedAt = glxyDateValues(found.Text())
		}
	}
	if existing, ok := seen[fullURL]; ok {
		// A notice often appears in the aggregate tab and its specific tab.
		// Keep one item and retain the first (aggregate-tab) provenance.
		if (*items)[existing].Date == "" && date != "" {
			(*items)[existing].Date = date
			(*items)[existing].PublishedAt = publishedAt
		}
		return
	}
	seen[fullURL] = len(*items)
	*items = append(*items, model.NewsItem{
		Title:       title,
		URL:         fullURL,
		Date:        date,
		PublishedAt: publishedAt,
		Type:        typ,
		ParsedAt:    time.Now(),
	})
}

func glxyArticleURL(baseURL, href string) (string, bool) {
	fullURL := cleanURL(resolveURL(baseURL, strings.TrimSpace(href)))
	parsed, err := url.Parse(fullURL)
	if err != nil || parsed.Host == "" || !glxyArticlePathRE.MatchString(parsed.Path) {
		return "", false
	}
	base, err := url.Parse(baseURL)
	if err != nil || base.Host == "" || !strings.EqualFold(parsed.Host, base.Host) {
		return "", false
	}
	if !isValidNewsURL(fullURL) {
		return "", false
	}
	return fullURL, true
}

func glxyListType(doc *goquery.Document) string {
	if doc == nil {
		return ""
	}
	return strings.Join(strings.Fields(doc.Find(`meta[name="pageTitle"]`).AttrOr("content", "")), " ")
}

// glxyDateValues intentionally leaves PublishedAt empty for date-only source
// values. The shared normalizer otherwise invents midnight, while this site
// does not publish a clock on its current list/detail metadata.
func glxyDateValues(raw string) (string, string) {
	raw = strings.Join(strings.Fields(strings.TrimSpace(raw)), " ")
	if raw == "" {
		return "", ""
	}
	normalized := normalizePublishedAt(raw)
	if len(normalized) < 10 {
		return "", ""
	}
	date := normalized[:10]
	if glxyClockRE.MatchString(raw) {
		return date, normalized
	}
	return date, ""
}

func glxyArticleType(doc *goquery.Document) string {
	if doc == nil {
		return ""
	}
	typ := ""
	doc.Find(".nav-b a").Each(func(_ int, link *goquery.Selection) {
		candidate := strings.Join(strings.Fields(link.Text()), " ")
		if candidate == "" || candidate == "首页" || candidate == "学院首页" || candidate == "新闻通知" {
			return
		}
		typ = candidate
	})
	return typ
}

func parseGlxyArticle(raw []byte, baseURL string) (*model.Article, error) {
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil {
		return nil, fmt.Errorf("parse glxy article: %w", err)
	}
	if glxyLooksLikeErrorPage(doc) {
		return nil, fmt.Errorf("glxy article is an error or verification page")
	}
	pageType := strings.TrimSpace(doc.Find(`meta[name="pageType"]`).AttrOr("content", ""))
	if pageType != "" && pageType != "3" {
		return nil, fmt.Errorf("glxy page is not an article (pageType %q)", pageType)
	}

	scope := doc.Find(`form[name="_newscontent_fromname"]`).First()
	if scope.Length() == 0 {
		return nil, fmt.Errorf("glxy article has no article form")
	}
	title := scope.Find(".article-tt, .newxq-boxy1 h1, h1").First()
	content := scope.Find(".v_news_content").First()
	if title.Length() == 0 || strings.TrimSpace(title.Text()) == "" {
		return nil, fmt.Errorf("glxy article has no title")
	}
	if content.Length() == 0 {
		return nil, fmt.Errorf("glxy article has no content container")
	}
	if strings.TrimSpace(content.Text()) == "" && content.Find("img, a, table").Length() == 0 {
		return nil, fmt.Errorf("glxy article has empty content")
	}

	article, err := parseBodaArticle(raw, baseURL)
	if err != nil {
		return nil, err
	}
	article.Title = strings.Join(strings.Fields(title.Text()), " ")
	if typ := glxyArticleType(doc); typ != "" {
		article.Type = typ
	}
	metaDate := ""
	if meta := scope.Find(".article-sm").First(); meta.Length() > 0 {
		if date, publishedAt := glxyDateValues(meta.Text()); date != "" {
			metaDate = date
			article.Date = date
			article.PublishedAt = publishedAt
		}
	}
	if metaDate == "" && article.Date != "" {
		if date, publishedAt := glxyDateValues(article.Date); date != "" {
			article.Date = date
			article.PublishedAt = publishedAt
		}
	}
	appendGlxyAttachments(article, scope, baseURL)
	resolveGlxyContentHTML(article, content, baseURL)
	return article, nil
}

func appendGlxyAttachments(article *model.Article, scope *goquery.Selection, baseURL string) {
	if article == nil || scope == nil || scope.Length() == 0 {
		return
	}
	seen := make(map[string]bool, len(article.Attachments))
	for _, attachment := range article.Attachments {
		seen[attachment.URL] = true
	}
	scope.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		href := strings.TrimSpace(anchor.AttrOr("href", ""))
		if !glxyLooksLikeAttachmentLink(anchor, href) {
			return
		}
		resolved := cleanURL(resolveURL(baseURL, href))
		if resolved == "" || seen[resolved] {
			return
		}
		name := glxyAttachmentName(anchor, resolved)
		if name == "" {
			return
		}
		seen[resolved] = true
		article.Attachments = append(article.Attachments, model.Attachment{Name: name, URL: resolved})
	})
}

func glxyLooksLikeAttachmentLink(anchor *goquery.Selection, href string) bool {
	if anchor == nil || anchor.Length() == 0 || href == "" {
		return false
	}
	lowerHref := strings.ToLower(href)
	if strings.Contains(lowerHref, "download.jsp") || strings.Contains(lowerHref, "downloadattachurl") {
		return true
	}
	if _, ok := anchor.Attr("download"); ok {
		return true
	}
	return glxyAttachmentRE.MatchString(href)
}

func glxyAttachmentName(anchor *goquery.Selection, resolved string) string {
	for _, attribute := range []string{"download", "data-filename", "data-name", "name", "title"} {
		if value := strings.Join(strings.Fields(htmlstd.UnescapeString(anchor.AttrOr(attribute, ""))), " "); value != "" {
			return value
		}
	}
	if value := strings.Join(strings.Fields(htmlstd.UnescapeString(anchor.Text())), " "); value != "" {
		return value
	}
	parsed, err := url.Parse(resolved)
	if err != nil {
		return ""
	}
	name := path.Base(parsed.Path)
	if name == "." || name == "/" || name == "" {
		return ""
	}
	if decoded, err := url.PathUnescape(name); err == nil {
		name = decoded
	}
	return name
}

func resolveGlxyContentHTML(article *model.Article, content *goquery.Selection, baseURL string) {
	if article == nil || content == nil || content.Length() == 0 {
		return
	}
	clone := content.Clone()
	clone.Find("img[src]").Each(func(_ int, image *goquery.Selection) {
		image.SetAttr("src", cleanURL(resolveURL(baseURL, image.AttrOr("src", ""))))
	})
	clone.Find("a[href]").Each(func(_ int, anchor *goquery.Selection) {
		href := anchor.AttrOr("href", "")
		if glxyLooksLikeAttachmentLink(anchor, href) {
			anchor.SetAttr("href", cleanURL(resolveURL(baseURL, href)))
		}
	})
	if htmlText, err := clone.Html(); err == nil {
		article.ContentHTML = htmlText
	}
}

func glxyIsHomepage(doc *goquery.Document) bool {
	if doc == nil {
		return false
	}
	pageType := strings.TrimSpace(doc.Find(`meta[name="pageType"]`).AttrOr("content", ""))
	return pageType == "1" || doc.Find(".page-one, .page-tow, .page-two, .page-three, .page-four, .page-five").Length() > 0
}

func glxyLooksLikeErrorPage(doc *goquery.Document) bool {
	if doc == nil {
		return true
	}
	title := strings.ToLower(strings.Join(strings.Fields(doc.Find("title").First().Text()), " "))
	for _, marker := range []string{"404", "403", "access denied", "not found", "页面不存在", "请求错误", "安全验证", "滑块验证", "验证码", "登录"} {
		if strings.Contains(title, marker) {
			return true
		}
	}
	body := strings.ToLower(strings.Join(strings.Fields(doc.Find("body").First().Text()), " "))
	for _, marker := range []string{"请输入验证码", "安全验证", "页面不存在", "access denied", "404 not found"} {
		if strings.Contains(body, marker) {
			return true
		}
	}
	return false
}

func glxyListShape(doc *goquery.Document) bool {
	return doc != nil && doc.Find("ul.xw-ul, ul.dj_lb1").Length() > 0
}

func glxyTotalPagesFromHTML(raw []byte) int {
	if total := parseTotalPages(raw); total > 0 {
		return total
	}
	doc, err := goquery.NewDocumentFromReader(strings.NewReader(string(raw)))
	if err != nil || !glxyListShape(doc) {
		return 0
	}
	return 1
}

func glxyTotalPages(slug string) (int, error) {
	baseURL := glxyBaseURL
	if site := AllSites["glxy"]; site != nil && strings.TrimSpace(site.BaseURL) != "" {
		baseURL = site.BaseURL
	}
	firstURL := glxyPageURL(baseURL, slug, 1, 0, ".htm")
	body, err := fetch(firstURL)
	if err != nil && strings.HasSuffix(strings.ToLower(firstURL), ".htm") {
		body, err = fetch(strings.TrimSuffix(firstURL, ".htm") + ".html")
	}
	if err != nil {
		return 0, fmt.Errorf("glxy: read first page for %s: %w", slug, err)
	}
	doc, parseErr := goquery.NewDocumentFromReader(strings.NewReader(string(body)))
	if parseErr != nil || glxyLooksLikeErrorPage(doc) {
		return 0, fmt.Errorf("glxy: %s is not a valid list page", slug)
	}
	if !glxyListShape(doc) {
		return 0, fmt.Errorf("glxy: %s is not an article list", slug)
	}
	if total := glxyTotalPagesFromHTML(body); total > 0 {
		return total, nil
	}
	return 1, nil
}
